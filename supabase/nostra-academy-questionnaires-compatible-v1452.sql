returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.academy_quizzes_v143(course_id,title,pass_score,active)
  values(new.id,'Questionnaire théorique · ' || new.title,new.theory_pass_score,false)
  on conflict (course_id) do nothing;
  return new;
end;
$$;

