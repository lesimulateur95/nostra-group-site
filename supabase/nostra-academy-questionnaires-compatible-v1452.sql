create table if not exists public.academy_quizzes_v143 (
  id bigint generated by default as identity primary key,
  course_id bigint not null unique references public.academy_courses_v137(id) on delete cascade,
  title text not null,
  instructions text,
  pass_score numeric(5,2) not null default 70 check (pass_score between 0 and 100),
  max_attempts integer not null default 3 check (max_attempts between 1 and 20),
  time_limit_minutes integer not null default 20 check (time_limit_minutes between 0 and 180),
  question_count integer not null default 0 check (question_count between 0 and 200),
  randomize_questions boolean not null default true,
  show_correction boolean not null default true,
  active boolean not null default false,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.academy_quiz_questions_v143 (
  id bigint generated by default as identity primary key,
  quiz_id bigint not null references public.academy_quizzes_v143(id) on delete cascade,
  prompt text not null,
  option_a text not null,
  option_b text not null,
  option_c text,
  option_d text,
  correct_option text not null check (correct_option in ('A','B','C','D')),
  explanation text,
  points integer not null default 1 check (points between 1 and 100),
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists academy_quiz_questions_quiz_v143_idx
  on public.academy_quiz_questions_v143(quiz_id,active,sort_order,id);

create table if not exists public.academy_quiz_attempts_v143 (
  id bigint generated by default as identity primary key,
  quiz_id bigint not null references public.academy_quizzes_v143(id) on delete cascade,
  enrollment_id bigint not null references public.academy_enrollments_v137(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  attempt_number integer not null,
  question_ids bigint[] not null default '{}'::bigint[],
  status text not null default 'in_progress' check (status in ('in_progress','passed','failed','expired')),
  score numeric(5,2),
  correct_count integer not null default 0,
  total_questions integer not null default 0,
  started_at timestamptz not null default now(),
  submitted_at timestamptz,
  unique(quiz_id,enrollment_id,attempt_number)
);

create index if not exists academy_quiz_attempts_user_v143_idx
  on public.academy_quiz_attempts_v143(user_id,started_at desc);
create index if not exists academy_quiz_attempts_enrollment_v143_idx
  on public.academy_quiz_attempts_v143(enrollment_id,quiz_id,attempt_number desc);

create table if not exists public.academy_quiz_answers_v143 (
  id bigint generated by default as identity primary key,
  attempt_id bigint not null references public.academy_quiz_attempts_v143(id) on delete cascade,
  question_id bigint not null references public.academy_quiz_questions_v143(id) on delete restrict,
  selected_option text check (selected_option in ('A','B','C','D')),
  is_correct boolean not null default false,
  points_awarded numeric(8,2) not null default 0,
  answered_at timestamptz not null default now(),
  unique(attempt_id,question_id)
);

alter table public.academy_enrollments_v137
  add column if not exists theory_quiz_passed_at timestamptz,
  add column if not exists theory_quiz_attempt_id bigint;

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'academy_enrollments_theory_quiz_attempt_v143_fkey'
  ) then
    alter table public.academy_enrollments_v137
      add constraint academy_enrollments_theory_quiz_attempt_v143_fkey
      foreign key (theory_quiz_attempt_id)
      references public.academy_quiz_attempts_v143(id)
      on delete set null;
  end if;
