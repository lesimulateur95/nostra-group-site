create or replace function public.academy_submit_quiz_v143(p_attempt_id bigint, p_answers jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_attempt public.academy_quiz_attempts_v143%rowtype;
  v_quiz public.academy_quizzes_v143%rowtype;
  v_course public.academy_courses_v137%rowtype;
  v_question public.academy_quiz_questions_v143%rowtype;
  v_selected text;
  v_total numeric := 0;
  v_awarded numeric := 0;
  v_score numeric(5,2) := 0;
  v_correct integer := 0;
  v_status text;
  v_required_score numeric(5,2);
begin
  if v_uid is null then raise exception using message='not_authenticated'; end if;
  if p_answers is null or jsonb_typeof(p_answers) <> 'object' then
    raise exception using message='invalid_answers';
  end if;

  select * into v_attempt
  from public.academy_quiz_attempts_v143
  where id=p_attempt_id
  for update;
  if not found then raise exception using message='attempt_not_found'; end if;
  if v_attempt.user_id <> v_uid then raise exception using message='forbidden'; end if;
  if v_attempt.status <> 'in_progress' then return public.academy_get_quiz_attempt_v143(v_attempt.id); end if;

  select * into v_quiz from public.academy_quizzes_v143 where id=v_attempt.quiz_id;
  select * into v_course from public.academy_courses_v137 where id=v_quiz.course_id;

  if v_quiz.time_limit_minutes > 0
     and now() > v_attempt.started_at + make_interval(mins => v_quiz.time_limit_minutes) then
    update public.academy_quiz_attempts_v143
    set status='expired',score=0,correct_count=0,submitted_at=now()
    where id=v_attempt.id;
    return public.academy_get_quiz_attempt_v143(v_attempt.id);
  end if;

  delete from public.academy_quiz_answers_v143 where attempt_id=v_attempt.id;

  for v_question in
    select * from public.academy_quiz_questions_v143
    where id=any(v_attempt.question_ids)
  loop
    v_total := v_total + v_question.points;
    v_selected := upper(nullif(trim(coalesce(p_answers ->> v_question.id::text,'')),''));
    if v_selected not in ('A','B','C','D') then v_selected := null; end if;

    if v_selected = v_question.correct_option then
      v_awarded := v_awarded + v_question.points;
      v_correct := v_correct + 1;
    end if;

    insert into public.academy_quiz_answers_v143(
      attempt_id,question_id,selected_option,is_correct,points_awarded
    ) values(
      v_attempt.id,v_question.id,v_selected,
      v_selected = v_question.correct_option,
      case when v_selected = v_question.correct_option then v_question.points else 0 end
    );
  end loop;

  if v_total > 0 then v_score := round((v_awarded / v_total) * 100,2); end if;
  v_required_score := greatest(v_quiz.pass_score,v_course.theory_pass_score);
  v_status := case when v_score >= v_required_score then 'passed' else 'failed' end;

  update public.academy_quiz_attempts_v143
  set status=v_status,score=v_score,correct_count=v_correct,submitted_at=now()
  where id=v_attempt.id;

  update public.academy_enrollments_v137
  set theory_score = case
        when theory_score is null then v_score
        else greatest(theory_score,v_score)
      end,
      theory_quiz_passed_at = case when v_status='passed' then now() else theory_quiz_passed_at end,
      theory_quiz_attempt_id = case when v_status='passed' then v_attempt.id else theory_quiz_attempt_id end,
      status = case when status='accepted' then 'training' else status end,
      updated_at=now()
  where id=v_attempt.enrollment_id;

  return public.academy_get_quiz_attempt_v143(v_attempt.id);
end;
$$;

grant execute on function public.academy_submit_quiz_v143(bigint,jsonb) to authenticated;

-- ---------------------------------------------------------------------------
-- 6. BLOQUER LA VALIDATION D'UNE FORMATION SI LE QCM ACTIF N'EST PAS RÉUSSI
-- ---------------------------------------------------------------------------

create or replace function public.academy_require_quiz_before_pass_v143()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_quiz_id bigint;
begin
  if new.status <> 'passed' then return new; end if;

  select id into v_quiz_id
  from public.academy_quizzes_v143
  where course_id=new.course_id and active=true
  limit 1;

  if v_quiz_id is null then return new; end if;

  if not exists (
    select 1 from public.academy_quiz_attempts_v143
    where quiz_id=v_quiz_id
      and enrollment_id=new.id
      and status='passed'
  ) then
    raise exception using message='academy_quiz_required';
  end if;

  return new;
end;
$$;

drop trigger if exists academy_require_quiz_before_pass_v143 on public.academy_enrollments_v137;
create trigger academy_require_quiz_before_pass_v143
before update of status on public.academy_enrollments_v137
for each row execute function public.academy_require_quiz_before_pass_v143();

commit;
