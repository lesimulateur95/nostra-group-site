-- ---------------------------------------------------------------------------
-- 3. DÉMARRER UN QUESTIONNAIRE
-- ---------------------------------------------------------------------------

create or replace function public.academy_start_quiz_v143(p_quiz_id bigint)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_quiz public.academy_quizzes_v143%rowtype;
  v_enrollment public.academy_enrollments_v137%rowtype;
  v_existing public.academy_quiz_attempts_v143%rowtype;
  v_attempt_count integer;
  v_attempt_id bigint;
  v_question_ids bigint[];
  v_limit integer;
begin
  if v_uid is null then raise exception using message='not_authenticated'; end if;

  select * into v_quiz
  from public.academy_quizzes_v143
  where id = p_quiz_id and active = true;
  if not found then raise exception using message='quiz_closed'; end if;

  select * into v_enrollment
  from public.academy_enrollments_v137
  where course_id = v_quiz.course_id
    and user_id = v_uid
  limit 1;
  if not found then raise exception using message='enrollment_required'; end if;
  if v_enrollment.status not in ('accepted','training') then
    raise exception using message='training_not_open';
  end if;

  -- Une tentative en cours est reprise. Si son chrono est dépassé, elle devient expirée.
  select * into v_existing
  from public.academy_quiz_attempts_v143
  where quiz_id = v_quiz.id
    and enrollment_id = v_enrollment.id
    and status = 'in_progress'
  order by attempt_number desc
  limit 1;

  if found then
    if v_quiz.time_limit_minutes > 0
       and now() > v_existing.started_at + make_interval(mins => v_quiz.time_limit_minutes) then
      update public.academy_quiz_attempts_v143
      set status='expired', score=0, submitted_at=now()
      where id=v_existing.id;
    else
      return v_existing.id;
    end if;
  end if;

  if exists (
    select 1 from public.academy_quiz_attempts_v143
    where quiz_id=v_quiz.id and enrollment_id=v_enrollment.id and status='passed'
  ) then
    raise exception using message='quiz_already_passed';
  end if;

  select count(*) into v_attempt_count
  from public.academy_quiz_attempts_v143
  where quiz_id=v_quiz.id
    and enrollment_id=v_enrollment.id
    and status in ('passed','failed','expired');
  if v_attempt_count >= v_quiz.max_attempts then
    raise exception using message='max_attempts_reached';
  end if;

  v_limit := case when v_quiz.question_count > 0 then v_quiz.question_count else 2147483647 end;

  if v_quiz.randomize_questions then
    select coalesce(array_agg(x.id), '{}'::bigint[])
    into v_question_ids
    from (
      select q.id
      from public.academy_quiz_questions_v143 q
      where q.quiz_id=v_quiz.id and q.active=true
      order by random()
      limit v_limit
    ) x;
  else
    select coalesce(array_agg(x.id order by x.sort_order,x.id), '{}'::bigint[])
    into v_question_ids
    from (
      select q.id,q.sort_order
      from public.academy_quiz_questions_v143 q
      where q.quiz_id=v_quiz.id and q.active=true
      order by q.sort_order,q.id
      limit v_limit
    ) x;
  end if;

  if coalesce(array_length(v_question_ids,1),0) = 0 then
    raise exception using message='quiz_has_no_questions';
  end if;

  insert into public.academy_quiz_attempts_v143(
    quiz_id,enrollment_id,user_id,attempt_number,question_ids,total_questions
  ) values(
    v_quiz.id,v_enrollment.id,v_uid,v_attempt_count+1,v_question_ids,array_length(v_question_ids,1)
  ) returning id into v_attempt_id;

  update public.academy_enrollments_v137
  set status = case when status='accepted' then 'training' else status end,
      updated_at=now()
  where id=v_enrollment.id;

  return v_attempt_id;
end;
$$;

grant execute on function public.academy_start_quiz_v143(bigint) to authenticated;

-- ---------------------------------------------------------------------------
-- 4. LIRE UNE TENTATIVE SANS EXPOSER LA CORRECTION AVANT LA FIN
-- ---------------------------------------------------------------------------

create or replace function public.academy_get_quiz_attempt_v143(p_attempt_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_attempt public.academy_quiz_attempts_v143%rowtype;
  v_quiz public.academy_quizzes_v143%rowtype;
  v_course public.academy_courses_v137%rowtype;
  v_can_correct boolean := false;
  v_questions jsonb;
begin
  if v_uid is null then raise exception using message='not_authenticated'; end if;

  select * into v_attempt from public.academy_quiz_attempts_v143 where id=p_attempt_id;
  if not found then raise exception using message='attempt_not_found'; end if;
  if v_attempt.user_id <> v_uid and not public.nostra_v137_has_any_role(array['manager','commissioner']) then
    raise exception using message='forbidden';
  end if;

  select * into v_quiz from public.academy_quizzes_v143 where id=v_attempt.quiz_id;
  select * into v_course from public.academy_courses_v137 where id=v_quiz.course_id;
  v_can_correct := v_attempt.status <> 'in_progress' and (v_quiz.show_correction or v_attempt.status='passed');

  select coalesce(jsonb_agg(
    jsonb_build_object(
      'id', q.id,
      'prompt', q.prompt,
      'optionA', q.option_a,
      'optionB', q.option_b,
      'optionC', q.option_c,
      'optionD', q.option_d,
      'points', q.points,
      'selectedOption', a.selected_option,
      'isCorrect', case when v_attempt.status <> 'in_progress' then a.is_correct else null end,
      'correctOption', case when v_can_correct then q.correct_option else null end,
      'explanation', case when v_can_correct then q.explanation else null end
    ) order by array_position(v_attempt.question_ids,q.id)
  ), '[]'::jsonb)
  into v_questions
  from public.academy_quiz_questions_v143 q
  left join public.academy_quiz_answers_v143 a
    on a.attempt_id=v_attempt.id and a.question_id=q.id
  where q.id = any(v_attempt.question_ids);

  return jsonb_build_object(
    'id', v_attempt.id,
    'status', v_attempt.status,
    'score', v_attempt.score,
    'attemptNumber', v_attempt.attempt_number,
    'startedAt', v_attempt.started_at,
    'submittedAt', v_attempt.submitted_at,
    'correctCount', v_attempt.correct_count,
    'totalQuestions', v_attempt.total_questions,
    'quizId', v_quiz.id,
    'quizTitle', v_quiz.title,
    'instructions', v_quiz.instructions,
    'timeLimitMinutes', v_quiz.time_limit_minutes,
    'passScore', greatest(v_quiz.pass_score,v_course.theory_pass_score),
    'maxAttempts', v_quiz.max_attempts,
    'courseId', v_course.id,
    'courseTitle', v_course.title,
    'questions', v_questions
  );
end;
$$;

grant execute on function public.academy_get_quiz_attempt_v143(bigint) to authenticated;

