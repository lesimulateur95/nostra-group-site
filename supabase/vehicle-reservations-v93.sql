create or replace function public.review_vehicle_reservation_v93(
  p_reservation_id bigint,
  p_decision text,
  p_admin_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_reservation public.vehicle_reservations%rowtype;
  v_vehicle public.catalog_vehicles%rowtype;
  v_balance_total numeric(14,2);
  v_image_url text;
begin
  if not public.nostra_can_manage_vehicle_reservations_v93() then
    raise exception using message = 'forbidden';
  end if;
  if coalesce(p_decision, '') not in ('approve', 'reject') then
    raise exception using message = 'invalid_decision';
  end if;

  select * into v_reservation
  from public.vehicle_reservations
  where id = p_reservation_id
  for update;
  if not found then raise exception using message = 'reservation_not_found'; end if;

  select * into v_vehicle
  from public.catalog_vehicles
  where id = v_reservation.vehicle_id;
  if not found then raise exception using message = 'vehicle_unavailable'; end if;

  if p_decision = 'reject' then
    if v_reservation.status not in ('pending_validation', 'balance_due') then
      raise exception using message = 'reservation_not_reviewable';
    end if;

    delete from public.cart_items
    where reservation_id = v_reservation.id
      and item_type = 'reservation_balance';

    if v_reservation.stock_reserved then
      update public.catalog_vehicles
      set stock_quantity = stock_quantity + v_reservation.quantity,
          updated_at = now()
      where id = v_reservation.vehicle_id;
    end if;

    update public.vehicle_reservations
    set status = 'rejected',
        stock_reserved = false,
        admin_note = nullif(btrim(coalesce(p_admin_note, '')), ''),
        rejected_at = now(),
        updated_at = now()
    where id = v_reservation.id;

    if v_reservation.catalog_type = 'used' then
      update public.catalog_vehicles
      set used_vehicle_status = case when stock_quantity > 0 then 'available' else 'sold' end,
          updated_at = now()
      where id = v_reservation.vehicle_id;
      if to_regclass('public.used_vehicle_details') is not null then
        execute 'update public.used_vehicle_details set sale_status = case when (select stock_quantity from public.catalog_vehicles where id = $1) > 0 then ''available'' else ''sold'' end, updated_at = now() where vehicle_id = $1'
        using v_reservation.vehicle_id;
      end if;
    end if;

    return jsonb_build_object('status', 'rejected');
  end if;

  if v_reservation.status not in ('pending_validation', 'balance_due') then
    raise exception using message = 'reservation_not_reviewable';
  end if;

  v_balance_total := v_reservation.balance_amount + v_reservation.delivery_fee;
  v_image_url := case
    when jsonb_typeof(v_vehicle.images) = 'array' and jsonb_array_length(v_vehicle.images) > 0
    then v_vehicle.images -> 0 ->> 'url'
    else null
  end;

  -- Une validation répétée remet proprement le même solde dans le panier,
  -- sans créer plusieurs lignes pour une seule réservation.
  delete from public.cart_items
  where user_id = v_reservation.user_id
    and reservation_id = v_reservation.id
    and item_type = 'reservation_balance';

  insert into public.cart_items (
    user_id, vehicle_id, related_vehicle_id, reservation_id, item_type,
    delivery_mode, delivery_address, delivery_phone, item_name, quantity,
    unit_price, original_unit_price, image_url, locked
  ) values (
    v_reservation.user_id, v_reservation.vehicle_id, v_reservation.vehicle_id,
    v_reservation.id, 'reservation_balance', v_reservation.delivery_mode,
    v_reservation.delivery_address, v_reservation.delivery_phone,
    'Solde réservation — ' || v_reservation.vehicle_name,
    1, v_balance_total, v_reservation.vehicle_price, v_image_url, true
  );

  update public.vehicle_reservations
  set status = 'balance_due',
      admin_note = nullif(btrim(coalesce(p_admin_note, '')), ''),
      validated_at = coalesce(validated_at, now()),
      balance_added_at = now(),
      updated_at = now()
  where id = v_reservation.id;

  return jsonb_build_object('status', 'balance_due', 'balance_added', v_balance_total);
end;
$$;

