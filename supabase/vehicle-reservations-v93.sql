create or replace function public.checkout_vehicle_reservation_deposits_v93(
  p_customer_name text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_line record;
  v_vehicle public.catalog_vehicles%rowtype;
  v_reservation_id bigint;
  v_reservation_number text;
  v_count integer := 0;
  v_deposit numeric(14,2);
  v_balance numeric(14,2);
  v_catalog_type text;
begin
  if v_user_id is null then raise exception using message = 'not_authenticated'; end if;
  if not exists (
    select 1 from public.cart_items
    where user_id = v_user_id and item_type = 'reservation_deposit'
  ) then raise exception using message = 'empty_reservation_cart'; end if;

  for v_line in
    select * from public.cart_items
    where user_id = v_user_id and item_type = 'reservation_deposit'
    order by id
    for update
  loop
    select * into v_vehicle
    from public.catalog_vehicles
    where id = v_line.vehicle_id and published = true
    for update;

    if not found then raise exception using message = 'vehicle_unavailable'; end if;
    if v_vehicle.stock_quantity < 1 then raise exception using message = 'insufficient_stock'; end if;
    if exists (
      select 1 from public.vehicle_reservations
      where user_id = v_user_id
        and vehicle_id = v_vehicle.id
        and status in ('pending_validation', 'balance_due', 'paid_full')
    ) then raise exception using message = 'reservation_already_exists'; end if;

    v_catalog_type := coalesce(to_jsonb(v_vehicle) ->> 'catalog_type', 'standard');
    if coalesce(v_line.delivery_mode, '') not in ('showroom', 'home') then
      raise exception using message = 'invalid_delivery_mode';
    end if;
    if v_catalog_type = 'heavy' and v_line.delivery_mode = 'home' then
      raise exception using message = 'heavy_home_delivery_disabled';
    end if;
    if v_line.delivery_mode = 'home'
       and length(btrim(coalesce(v_line.delivery_address, ''))) < 5 then
      raise exception using message = 'invalid_delivery_address';
    end if;
    if v_line.delivery_mode = 'home'
       and length(btrim(coalesce(v_line.delivery_phone, ''))) < 3 then
      raise exception using message = 'invalid_delivery_phone';
    end if;
    if v_catalog_type = 'used'
       and coalesce(to_jsonb(v_vehicle) ->> 'used_vehicle_status', 'available') <> 'available' then
      raise exception using message = 'used_vehicle_unavailable';
    end if;

    v_deposit := round(v_vehicle.price * 0.15, 2);
    v_balance := round(v_vehicle.price - v_deposit, 2);
    v_reservation_number := 'RES-' || to_char(clock_timestamp(), 'YYYYMMDD') || '-' || upper(substr(md5(random()::text || clock_timestamp()::text || v_line.id::text), 1, 7));

    update public.catalog_vehicles
    set stock_quantity = stock_quantity - 1, updated_at = now()
    where id = v_vehicle.id;

    insert into public.vehicle_reservations (
      reservation_number, user_id, vehicle_id, customer_name, vehicle_name,
      catalog_type, quantity, vehicle_price, deposit_percent, deposit_amount,
      balance_amount, delivery_mode, delivery_fee, delivery_address,
      delivery_phone, status, stock_reserved, deposit_paid_at, created_at,
      updated_at
    ) values (
      v_reservation_number, v_user_id, v_vehicle.id,
      coalesce(nullif(btrim(p_customer_name), ''), 'Client Nostra Motors'),
      btrim(v_vehicle.brand || ' ' || v_vehicle.model), v_catalog_type, 1,
      v_vehicle.price, 15, v_deposit, v_balance,
      coalesce(v_line.delivery_mode, 'showroom'),
      case when v_line.delivery_mode = 'home' then 75000 else 0 end,
      case when v_line.delivery_mode = 'home' then v_line.delivery_address else null end,
      case when v_line.delivery_mode = 'home' then v_line.delivery_phone else null end,
      'pending_validation', true, now(), now(), now()
    ) returning id into v_reservation_id;

    if v_catalog_type = 'used' and v_vehicle.stock_quantity - 1 <= 0 then
      update public.catalog_vehicles
      set used_vehicle_status = 'reserved', updated_at = now()
      where id = v_vehicle.id;
      if to_regclass('public.used_vehicle_details') is not null then
        execute 'update public.used_vehicle_details set sale_status = ''reserved'', updated_at = now() where vehicle_id = $1'
        using v_vehicle.id;
      end if;
    end if;

    delete from public.cart_items where id = v_line.id;
    v_count := v_count + 1;
  end loop;

  return jsonb_build_object('reservations_created', v_count);
end;
$$;

