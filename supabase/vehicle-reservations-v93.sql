alter table public.cart_items add column if not exists locked boolean not null default false;
alter table public.cart_items add column if not exists original_unit_price numeric(14,2);

-- Remplace toute ancienne contrainte portant sur item_type.
do $$
declare
  constraint_row record;
begin
  for constraint_row in
    select conname
    from pg_constraint
    where conrelid = 'public.cart_items'::regclass
      and contype = 'c'
      and pg_get_constraintdef(oid) ilike '%item_type%'
  loop
    execute format(
      'alter table public.cart_items drop constraint if exists %I',
      constraint_row.conname
    );
  end loop;
end;
$$;

alter table public.cart_items
  add constraint cart_items_item_type_v93_check
  check (item_type in ('vehicle', 'delivery', 'reservation_deposit', 'reservation_balance')) not valid;
alter table public.cart_items validate constraint cart_items_item_type_v93_check;

-- Clé étrangère ajoutée après la création de la table.
do $$
begin
  if exists (
    select 1 from pg_constraint
    where conname = 'cart_items_reservation_id_fkey'
      and conrelid = 'public.cart_items'::regclass
  ) then
    alter table public.cart_items drop constraint cart_items_reservation_id_fkey;
  end if;

  alter table public.cart_items
    add constraint cart_items_reservation_id_fkey
    foreign key (reservation_id)
    references public.vehicle_reservations(id)
    on delete cascade;
end;
$$;

create index if not exists cart_items_reservation_v93_idx
  on public.cart_items (user_id, reservation_id, item_type);

