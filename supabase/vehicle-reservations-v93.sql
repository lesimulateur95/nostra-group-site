create or replace function public.nostra_validate_used_order_v92()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  item jsonb;
  v_vehicle_id bigint;
  v_reservation_id bigint;
  vehicle_row public.catalog_vehicles%rowtype;
begin
  if tg_op = 'UPDATE' and not (old.status = 'cancelled' and new.status <> 'cancelled') then
    return new;
  end if;

  for item in select value from jsonb_array_elements(coalesce(new.items, '[]'::jsonb))
  loop
    if coalesce(item ->> 'item_type', 'vehicle') <> 'vehicle' then continue; end if;
    v_vehicle_id := nullif(item ->> 'vehicle_id', '')::bigint;
    if v_vehicle_id is null then continue; end if;

    select * into vehicle_row
    from public.catalog_vehicles
    where id = v_vehicle_id and catalog_type = 'used';

    if found and vehicle_row.used_vehicle_status <> 'available' then
      v_reservation_id := nullif(item ->> 'reservation_id', '')::bigint;
      if v_reservation_id is null or not exists (
        select 1 from public.vehicle_reservations reservation
        where reservation.id = v_reservation_id
          and reservation.user_id = new.user_id
          and reservation.vehicle_id = v_vehicle_id
          and reservation.status in ('balance_due', 'paid_full')
      ) then
        raise exception using message = 'used_vehicle_unavailable';
      end if;
    end if;
  end loop;
  return new;
end;
$$;

-- Synchronise l'état de la réservation avec la commande finale.
create or replace function public.nostra_sync_reservation_order_status_v93()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'DELETE' then
    update public.vehicle_reservations
    set status = 'cancelled',
        stock_reserved = false,
        final_order_id = null,
        updated_at = now()
    where final_order_id = old.id;
    return old;
  end if;

  update public.vehicle_reservations
  set status = case
        when new.status = 'completed' then 'completed'
        when new.status = 'cancelled' then 'cancelled'
        else 'paid_full'
      end,
      stock_reserved = case when new.status = 'cancelled' then false else stock_reserved end,
      updated_at = now()
  where final_order_id = new.id;
  return new;
end;
$$;

drop trigger if exists sync_reservation_order_status_v93 on public.orders;
create trigger sync_reservation_order_status_v93
  after update of status on public.orders
  for each row
  execute function public.nostra_sync_reservation_order_status_v93();

drop trigger if exists sync_reservation_order_delete_v93 on public.orders;
create trigger sync_reservation_order_delete_v93
  before delete on public.orders
  for each row
  execute function public.nostra_sync_reservation_order_status_v93();

