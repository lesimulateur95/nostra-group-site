-- NOSTRA GROUP — V93
-- Réservation / commande des véhicules avec acompte de 15 %.
-- Réexécutable : ne supprime aucune commande, réservation ou donnée existante.

begin;

-- ---------------------------------------------------------------------------
-- 1. Réservations véhicules
-- ---------------------------------------------------------------------------

create table if not exists public.vehicle_reservations (
  id bigint generated by default as identity primary key,
  reservation_number text not null unique,
  user_id uuid not null references auth.users(id) on delete cascade,
  vehicle_id bigint not null references public.catalog_vehicles(id) on delete restrict,
  customer_name text not null default '',
  vehicle_name text not null,
  catalog_type text not null default 'standard',
  quantity integer not null default 1 check (quantity > 0),
  vehicle_price numeric(14,2) not null check (vehicle_price >= 0),
  deposit_percent numeric(5,2) not null default 15 check (deposit_percent > 0 and deposit_percent < 100),
  deposit_amount numeric(14,2) not null check (deposit_amount >= 0),
  balance_amount numeric(14,2) not null check (balance_amount >= 0),
  delivery_mode text not null default 'showroom' check (delivery_mode in ('showroom', 'home')),
  delivery_fee numeric(14,2) not null default 0 check (delivery_fee >= 0),
  delivery_address text,
  delivery_phone text,
  status text not null default 'pending_validation'
    check (status in ('pending_validation', 'balance_due', 'paid_full', 'rejected', 'cancelled', 'completed')),
  admin_note text,
  stock_reserved boolean not null default true,
  deposit_paid_at timestamptz not null default now(),
  validated_at timestamptz,
  balance_added_at timestamptz,
  balance_paid_at timestamptz,
  rejected_at timestamptz,
  final_order_id bigint references public.orders(id) on delete set null,
  final_order_number text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists vehicle_reservations_user_v93_idx
  on public.vehicle_reservations (user_id, created_at desc);
create index if not exists vehicle_reservations_status_v93_idx
  on public.vehicle_reservations (status, created_at desc);
create index if not exists vehicle_reservations_vehicle_v93_idx
  on public.vehicle_reservations (vehicle_id, status);
create unique index if not exists vehicle_reservations_active_user_vehicle_v93_uq
  on public.vehicle_reservations (user_id, vehicle_id)
  where status in ('pending_validation', 'balance_due', 'paid_full');

