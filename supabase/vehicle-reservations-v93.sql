create or replace function public.add_vehicle_purchase_to_cart_v93(
  p_vehicle_id bigint,
  p_delivery_mode text,
  p_delivery_address text default null,
  p_delivery_phone text default null,
  p_purchase_mode text default 'order'
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_vehicle public.catalog_vehicles%rowtype;
  v_vehicle_line public.cart_items%rowtype;
  v_delivery_line public.cart_items%rowtype;
  v_next_quantity integer;
  v_image_url text;
  v_item_name text;
  v_deposit numeric(14,2);
begin
  if v_user_id is null then
    raise exception using message = 'not_authenticated';
  end if;

  if coalesce(p_delivery_mode, '') not in ('showroom', 'home') then
    raise exception using message = 'invalid_delivery_mode';
  end if;

  if coalesce(p_purchase_mode, '') not in ('order', 'reservation') then
    raise exception using message = 'invalid_purchase_mode';
  end if;

  select * into v_vehicle
  from public.catalog_vehicles
  where id = p_vehicle_id
    and published = true
  for share;

  if not found then
    raise exception using message = 'vehicle_unavailable';
  end if;

  if greatest(coalesce(v_vehicle.stock_quantity, 0), 0) <= 0 then
    raise exception using message = 'insufficient_stock';
  end if;

  if coalesce(to_jsonb(v_vehicle) ->> 'catalog_type', 'standard') = 'heavy'
     and p_delivery_mode = 'home' then
    raise exception using message = 'heavy_home_delivery_disabled';
  end if;

  if coalesce(to_jsonb(v_vehicle) ->> 'catalog_type', 'standard') = 'used'
     and coalesce(to_jsonb(v_vehicle) ->> 'used_vehicle_status', 'available') <> 'available' then
    raise exception using message = 'used_vehicle_unavailable';
  end if;

  if p_delivery_mode = 'home' and length(btrim(coalesce(p_delivery_address, ''))) < 5 then
    raise exception using message = 'invalid_delivery_address';
  end if;

  if p_delivery_mode = 'home' and length(btrim(coalesce(p_delivery_phone, ''))) < 3 then
    raise exception using message = 'invalid_delivery_phone';
  end if;

  v_item_name := btrim(v_vehicle.brand || ' ' || v_vehicle.model);
  v_image_url := case
    when jsonb_typeof(v_vehicle.images) = 'array'
      and jsonb_array_length(v_vehicle.images) > 0
    then v_vehicle.images -> 0 ->> 'url'
    else null
  end;

  if p_purchase_mode = 'reservation' then
    if exists (
      select 1 from public.vehicle_reservations
      where user_id = v_user_id
        and vehicle_id = p_vehicle_id
        and status in ('pending_validation', 'balance_due', 'paid_full')
    ) then
      raise exception using message = 'reservation_already_exists';
    end if;

    delete from public.cart_items
    where user_id = v_user_id
      and (
        (item_type = 'vehicle' and vehicle_id = p_vehicle_id)
        or (item_type = 'delivery' and related_vehicle_id = p_vehicle_id)
      );

    v_deposit := round(greatest(coalesce(v_vehicle.price, 0), 0) * 0.15, 2);

    -- Remplace un éventuel acompte non payé du même véhicule afin que le
    -- mode de livraison et les coordonnées restent toujours à jour.
    delete from public.cart_items
    where user_id = v_user_id
      and item_type = 'reservation_deposit'
      and vehicle_id = p_vehicle_id;

    insert into public.cart_items (
      user_id,
      vehicle_id,
      related_vehicle_id,
      reservation_id,
      item_type,
      delivery_mode,
      delivery_address,
      delivery_phone,
      item_name,
      quantity,
      unit_price,
      original_unit_price,
      image_url,
      locked
    ) values (
      v_user_id,
      p_vehicle_id,
      p_vehicle_id,
      null,
      'reservation_deposit',
      p_delivery_mode,
      case when p_delivery_mode = 'home' then btrim(p_delivery_address) else null end,
      case when p_delivery_mode = 'home' then btrim(p_delivery_phone) else null end,
      'Acompte 15 % — ' || v_item_name,
      1,
      v_deposit,
      v_vehicle.price,
      v_image_url,
      false
    );

    return jsonb_build_object(
      'purchase_mode', 'reservation',
      'vehicle_id', p_vehicle_id,
      'deposit_amount', v_deposit,
      'balance_amount', round(greatest(coalesce(v_vehicle.price, 0), 0) - v_deposit, 2)
    );
  end if;

  -- Commander au prix total : retire l'éventuel acompte non payé du même véhicule.
  delete from public.cart_items
  where user_id = v_user_id
    and item_type = 'reservation_deposit'
    and vehicle_id = p_vehicle_id;

  select * into v_vehicle_line
  from public.cart_items
  where user_id = v_user_id
    and item_type = 'vehicle'
    and vehicle_id = p_vehicle_id
  order by id
  limit 1
  for update;

  v_next_quantity := coalesce(v_vehicle_line.quantity, 0) + 1;
  if v_next_quantity > v_vehicle.stock_quantity then
    raise exception using message = 'insufficient_stock';
  end if;

  if v_vehicle_line.id is null then
    insert into public.cart_items (
      user_id, vehicle_id, related_vehicle_id, reservation_id, item_type,
      delivery_mode, delivery_address, delivery_phone, item_name, quantity,
      unit_price, original_unit_price, image_url, locked
    ) values (
      v_user_id, p_vehicle_id, null, null, 'vehicle', p_delivery_mode,
      case when p_delivery_mode = 'home' then btrim(p_delivery_address) else null end,
      case when p_delivery_mode = 'home' then btrim(p_delivery_phone) else null end,
      v_item_name, 1, v_vehicle.price, v_vehicle.price, v_image_url, false
    );
  else
    update public.cart_items
    set quantity = v_next_quantity,
        item_name = v_item_name,
        unit_price = v_vehicle.price,
        original_unit_price = v_vehicle.price,
        image_url = v_image_url,
        delivery_mode = p_delivery_mode,
        delivery_address = case when p_delivery_mode = 'home' then btrim(p_delivery_address) else null end,
        delivery_phone = case when p_delivery_mode = 'home' then btrim(p_delivery_phone) else null end
    where id = v_vehicle_line.id;
  end if;

  if p_delivery_mode = 'home' then
    select * into v_delivery_line
    from public.cart_items
    where user_id = v_user_id
      and item_type = 'delivery'
      and related_vehicle_id = p_vehicle_id
    order by id
    limit 1
    for update;

    if v_delivery_line.id is null then
      insert into public.cart_items (
        user_id, vehicle_id, related_vehicle_id, reservation_id, item_type,
        delivery_mode, delivery_address, delivery_phone, item_name, quantity,
        unit_price, original_unit_price, image_url, locked
      ) values (
        v_user_id, null, p_vehicle_id, null, 'delivery', 'home',
        btrim(p_delivery_address), btrim(p_delivery_phone),
        'Livraison à domicile — ' || v_item_name,
        1, 75000, 75000, null, false
      );
    else
      update public.cart_items
      set quantity = v_next_quantity,
          delivery_address = btrim(p_delivery_address),
          delivery_phone = btrim(p_delivery_phone),
          item_name = 'Livraison à domicile — ' || v_item_name,
          unit_price = 75000,
          original_unit_price = 75000
      where id = v_delivery_line.id;
    end if;
  else
    delete from public.cart_items
    where user_id = v_user_id
      and item_type = 'delivery'
      and related_vehicle_id = p_vehicle_id;
  end if;

  return jsonb_build_object(
    'purchase_mode', 'order',
    'vehicle_id', p_vehicle_id,
    'delivery_mode', p_delivery_mode,
    'delivery_price', case when p_delivery_mode = 'home' then 75000 else 0 end
  );
end;
$$;

