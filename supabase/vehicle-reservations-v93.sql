create or replace function public.checkout_vehicle_reservation_balances_v93()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_line record;
  v_reservation public.vehicle_reservations%rowtype;
  v_vehicle public.catalog_vehicles%rowtype;
  v_order_id bigint;
  v_order_number text;
  v_items jsonb;
  v_total numeric(14,2);
  v_count integer := 0;
begin
  if v_user_id is null then raise exception using message = 'not_authenticated'; end if;
  if not exists (
    select 1 from public.cart_items
    where user_id = v_user_id and item_type = 'reservation_balance'
  ) then raise exception using message = 'empty_balance_cart'; end if;

  for v_line in
    select * from public.cart_items
    where user_id = v_user_id and item_type = 'reservation_balance'
    order by id
    for update
  loop
    select * into v_reservation
    from public.vehicle_reservations
    where id = v_line.reservation_id
      and user_id = v_user_id
    for update;

    if not found or v_reservation.status <> 'balance_due' then
      raise exception using message = 'reservation_balance_unavailable';
    end if;

    select * into v_vehicle
    from public.catalog_vehicles
    where id = v_reservation.vehicle_id;
    if not found then raise exception using message = 'vehicle_unavailable'; end if;

    v_order_number := 'NR-' || to_char(clock_timestamp(), 'YYYYMMDD') || '-' || upper(substr(md5(random()::text || clock_timestamp()::text || v_reservation.id::text), 1, 7));
    v_total := v_reservation.vehicle_price + v_reservation.delivery_fee;
    v_items := jsonb_build_array(jsonb_build_object(
      'item_type', 'vehicle',
      'vehicle_id', v_reservation.vehicle_id,
      'reservation_id', v_reservation.id,
      'name', v_reservation.vehicle_name,
      'quantity', v_reservation.quantity,
      'unit_price', v_reservation.vehicle_price,
      'deposit_paid', v_reservation.deposit_amount,
      'balance_paid', v_reservation.balance_amount,
      'image_url', case when jsonb_typeof(v_vehicle.images) = 'array' and jsonb_array_length(v_vehicle.images) > 0 then v_vehicle.images -> 0 ->> 'url' else null end
    ));

    if v_reservation.delivery_mode = 'home' then
      v_items := v_items || jsonb_build_array(jsonb_build_object(
        'item_type', 'delivery',
        'vehicle_id', null,
        'related_vehicle_id', v_reservation.vehicle_id,
        'reservation_id', v_reservation.id,
        'name', 'Livraison à domicile — ' || v_reservation.vehicle_name,
        'delivery_address', v_reservation.delivery_address,
        'delivery_phone', v_reservation.delivery_phone,
        'quantity', v_reservation.quantity,
        'unit_price', v_reservation.delivery_fee,
        'image_url', null
      ));
    end if;

    insert into public.orders (
      user_id, order_number, customer_name, status, total, items,
      customer_note, stock_deducted, updated_at
    ) values (
      v_user_id, v_order_number, v_reservation.customer_name, 'pending',
      v_total, v_items,
      'Commande issue de la réservation ' || v_reservation.reservation_number,
      true, now()
    ) returning id into v_order_id;

    update public.vehicle_reservations
    set status = 'paid_full',
        balance_paid_at = now(),
        final_order_id = v_order_id,
        final_order_number = v_order_number,
        updated_at = now()
    where id = v_reservation.id;

    delete from public.cart_items where id = v_line.id;
    v_count := v_count + 1;
  end loop;

  return jsonb_build_object('orders_created', v_count);
end;
$$;

