  p_decision text,
  p_warranty_action text default null,
  p_staff_note text default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_req public.motors_vehicle_transfers_v164%rowtype;
  v_policy text;
  v_warranty_action text;
  v_vehicle_label text;
begin
  if not public.nostra_v164_has_permission('transfer_manage') then
    raise exception using message='forbidden';
  end if;

  if p_decision not in ('approved','rejected') then
    raise exception using message='invalid_decision';
  end if;

  select * into v_req
  from public.motors_vehicle_transfers_v164
  where id=p_request_id and status='pending'
  for update;

  if not found then raise exception using message='transfer_not_found'; end if;

  select warranty_transfer_policy into v_policy from public.motors_settings_v164 where id=1;
  v_warranty_action := coalesce(nullif(p_warranty_action,''), case when v_policy='cancel' then 'cancel' else 'transfer' end);

  if p_decision='rejected' then
    update public.motors_vehicle_transfers_v164
    set status='rejected', staff_note=nullif(p_staff_note,''), processed_by=auth.uid(), processed_at=now(), updated_at=now()
    where id=v_req.id;

    if to_regclass('public.user_notifications') is not null then
      insert into public.user_notifications(user_id,notification_type,title,message,target_url,source_type,source_id,priority,category)
      values(v_req.seller_user_id,'general','Transfert de véhicule refusé','La demande de transfert a été refusée par Nostra Motors.','/profil/garage/'||v_req.customer_vehicle_id,'vehicle_transfer_v164',v_req.id::text,'high','motors');
    end if;
    return;
  end if;

  if not exists(select 1 from public.customer_vehicles where id=v_req.customer_vehicle_id and user_id=v_req.seller_user_id and garage_status <> 'cancelled') then
    raise exception using message='vehicle_owner_changed';
  end if;

  select coalesce(nullif(btrim(concat_ws(' ',brand,model)),''),vehicle_name,'Véhicule Nostra')
  into v_vehicle_label
  from public.customer_vehicles where id=v_req.customer_vehicle_id;

  -- Les contrats en panier sont toujours annulés avant un changement de propriétaire.
  update public.motors_warranty_contracts_v163
  set status='cancelled', updated_at=now()
  where customer_vehicle_id=v_req.customer_vehicle_id and status='pending_payment';

  if v_warranty_action='transfer' then
    update public.motors_warranty_contracts_v163
    set user_id=v_req.target_user_id, updated_at=now()
    where customer_vehicle_id=v_req.customer_vehicle_id and status='active' and ends_at>now();
  else
    update public.motors_warranty_contracts_v163
    set status='cancelled', updated_at=now()
    where customer_vehicle_id=v_req.customer_vehicle_id and status='active';
  end if;

  update public.customer_vehicles
  set user_id=v_req.target_user_id, updated_at=now()
  where id=v_req.customer_vehicle_id;

  update public.motors_vehicle_maintenance_v164
  set owner_user_id=v_req.target_user_id, updated_at=now()
  where customer_vehicle_id=v_req.customer_vehicle_id;

  update public.motors_vehicle_transfers_v164
  set status='approved', warranty_action=v_warranty_action, staff_note=nullif(p_staff_note,''),
      processed_by=auth.uid(), processed_at=now(), updated_at=now()
  where id=v_req.id;

  if to_regclass('public.customer_vehicle_history') is not null then
    insert into public.customer_vehicle_history(customer_vehicle_id,event_type,status,title,details,created_at)
    values(v_req.customer_vehicle_id,'ownership_transfer','completed','Changement de propriétaire',
      'Transfert validé par Nostra Motors. Type : '||v_req.transfer_type||'. Nostra Care : '||v_warranty_action||'.',now());
  end if;

  if to_regclass('public.user_notifications') is not null then
    insert into public.user_notifications(user_id,notification_type,title,message,target_url,source_type,source_id,priority,category)
    values
      (v_req.seller_user_id,'general','Transfert de véhicule validé',v_vehicle_label||' a été retiré de ton garage.','/profil/garage','vehicle_transfer_v164',v_req.id::text,'high','motors'),
      (v_req.target_user_id,'general','Nouveau véhicule dans ton garage',v_vehicle_label||' est maintenant enregistré dans ton garage Nostra Motors.','/profil/garage/'||v_req.customer_vehicle_id,'vehicle_transfer_v164',v_req.id::text,'high','motors');
  end if;

  insert into public.motors_employee_audit_v164(actor_user_id,action_key,entity_type,entity_id,title,details)
  values(auth.uid(),'vehicle_transfer_approved','customer_vehicle',v_req.customer_vehicle_id::text,'Transfert véhicule validé',jsonb_build_object('request_id',v_req.id,'seller',v_req.seller_user_id,'buyer',v_req.target_user_id,'warranty_action',v_warranty_action));
end;
$$;

grant execute on function public.nostra_v164_process_vehicle_transfer(bigint,text,text,text) to authenticated;

