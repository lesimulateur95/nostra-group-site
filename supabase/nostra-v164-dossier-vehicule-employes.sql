create or replace function public.nostra_v164_has_permission(p_permission text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.nostra_v164_is_manager()
    or exists (
      select 1
      from public.motors_employees_v164 e
      where e.user_id = auth.uid()
        and e.active
        and coalesce(e.permissions, '{}'::jsonb) ? p_permission
        and coalesce((e.permissions ->> p_permission)::boolean, false)
    );
$$;

