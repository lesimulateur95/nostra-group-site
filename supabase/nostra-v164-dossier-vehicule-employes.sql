create or replace function public.nostra_v164_maintenance_event()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_title text;
  v_details text;
  v_notify boolean := true;
begin
  if new.mileage is not null then
    update public.customer_vehicles
    set current_mileage = greatest(coalesce(current_mileage,0), new.mileage), updated_at=now()
    where id=new.customer_vehicle_id;
  end if;

  if tg_op='INSERT' then
    v_title := 'Entretien Nostra · '||new.title;
    v_details := concat_ws(' · ', nullif(new.work_done,''), nullif(new.staff_comment,''),
      case when new.mileage is not null then new.mileage::text||' km' else null end);
  elsif old.deleted_at is null and new.deleted_at is not null then
    v_title := 'Entrée du carnet archivée';
    v_details := new.title;
  else
    v_title := 'Carnet d’entretien mis à jour · '||new.title;
    v_details := concat_ws(' · ', nullif(new.work_done,''), nullif(new.staff_comment,''),
      case when new.mileage is not null then new.mileage::text||' km' else null end);
  end if;

  if to_regclass('public.customer_vehicle_history') is not null then
    insert into public.customer_vehicle_history(customer_vehicle_id,event_type,status,title,details,created_at)
    values(new.customer_vehicle_id,'maintenance',new.status,v_title,nullif(v_details,''),now());
  end if;

  if tg_op = 'UPDATE' and old.deleted_at is null and new.deleted_at is not null then
    v_notify := false;
  end if;

  if to_regclass('public.user_notifications') is not null and v_notify then
    insert into public.user_notifications(user_id,notification_type,title,message,target_url,source_type,source_id,priority,category)
    values(new.owner_user_id,'maintenance',case when tg_op='INSERT' then 'Carnet d’entretien mis à jour' else 'Entretien Nostra mis à jour' end,
      new.title||case when new.staff_comment is not null and btrim(new.staff_comment)<>'' then ' · '||new.staff_comment else '' end,
      '/profil/garage/'||new.customer_vehicle_id,'maintenance_v164',new.id::text,'normal','motors');
  end if;

  return new;
end;
$$;

drop trigger if exists nostra_v164_maintenance_event on public.motors_vehicle_maintenance_v164;
create trigger nostra_v164_maintenance_event
after insert or update on public.motors_vehicle_maintenance_v164
for each row execute function public.nostra_v164_maintenance_event();

