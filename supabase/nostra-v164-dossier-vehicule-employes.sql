-- Nostra Care alimente aussi la timeline du véhicule au moment des changements
-- de statut importants (paiement, expiration, annulation).
create or replace function public.nostra_v164_warranty_history_event()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_title text;
  v_details text;
begin
  if new.status is not distinct from old.status then return new; end if;

  if new.status='active' then
    v_title := 'Nostra Care activé · '||new.plan_name;
    v_details := 'Contrat '||new.contract_number||' · '||new.duration_days||' jour(s) · '||new.amount||' €.';
  elsif new.status='expired' then
    v_title := 'Nostra Care expiré · '||new.plan_name;
    v_details := 'Le contrat '||new.contract_number||' est arrivé à expiration.';
  elsif new.status='cancelled' then
    v_title := 'Nostra Care annulé · '||new.plan_name;
    v_details := 'Le contrat '||new.contract_number||' a été annulé.';
  else
    return new;
  end if;

  if to_regclass('public.customer_vehicle_history') is not null then
    insert into public.customer_vehicle_history(customer_vehicle_id,event_type,status,title,details,created_at)
    values(new.customer_vehicle_id,'warranty',new.status,v_title,v_details,now());
  end if;

  if new.status='active' and to_regclass('public.user_notifications') is not null and not exists (
    select 1 from public.user_notifications n
    where n.user_id=new.user_id and n.source_type='warranty_active_v164' and n.source_id=new.id::text
  ) then
    insert into public.user_notifications(user_id,notification_type,title,message,target_url,source_type,source_id,priority,category)
    values(new.user_id,'contract','Nostra Care activé',new.plan_name||' est maintenant actif sur ton véhicule.','/profil/garage/'||new.customer_vehicle_id,'warranty_active_v164',new.id::text,'high','motors');
  end if;

  return new;
end;
$$;

drop trigger if exists nostra_v164_warranty_history_event on public.motors_warranty_contracts_v163;
create trigger nostra_v164_warranty_history_event
after update of status on public.motors_warranty_contracts_v163
for each row execute function public.nostra_v164_warranty_history_event();

-- -----------------------------------------------------------------------------
-- 6) Notifications intelligentes Nostra Care + entretien
-- -----------------------------------------------------------------------------
create or replace function public.nostra_v164_refresh_my_vehicle_notifications()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_count integer := 0;
  v_row record;
  v_days integer;
begin
  if v_uid is null then return 0; end if;
  if to_regclass('public.user_notifications') is null then return 0; end if;

  -- Expire les contrats arrivés à échéance.
  update public.motors_warranty_contracts_v163
  set status = 'expired', updated_at = now()
  where user_id = v_uid and status = 'active' and ends_at <= now();

  for v_row in
    select id, contract_number, plan_name, customer_vehicle_id, ends_at, status
    from public.motors_warranty_contracts_v163
    where user_id = v_uid and status in ('active','expired')
  loop
    v_days := ceil(extract(epoch from (v_row.ends_at - now())) / 86400.0)::integer;

    if v_row.status = 'active' and v_days between 2 and 7 and not exists (
      select 1 from public.user_notifications n
      where n.user_id=v_uid and n.source_type='warranty_7d_v164' and n.source_id=v_row.id::text
    ) then
      insert into public.user_notifications(user_id,notification_type,title,message,target_url,source_type,source_id,priority,category)
      values(v_uid,'contract','Nostra Care expire bientôt',v_row.plan_name||' expire dans '||v_days||' jour(s).','/profil/garage/'||v_row.customer_vehicle_id,'warranty_7d_v164',v_row.id::text,'high','motors');
      v_count := v_count + 1;
    end if;

    if v_row.status = 'active' and v_days between 0 and 1 and not exists (
      select 1 from public.user_notifications n
      where n.user_id=v_uid and n.source_type='warranty_1d_v164' and n.source_id=v_row.id::text
    ) then
      insert into public.user_notifications(user_id,notification_type,title,message,target_url,source_type,source_id,priority,category)
      values(v_uid,'contract','Nostra Care arrive à expiration','Ton contrat '||v_row.plan_name||' expire dans moins de 24 h.','/profil/garage/'||v_row.customer_vehicle_id,'warranty_1d_v164',v_row.id::text,'urgent','motors');
      v_count := v_count + 1;
    end if;

    if v_row.status = 'expired' and not exists (
      select 1 from public.user_notifications n
      where n.user_id=v_uid and n.source_type='warranty_expired_v164' and n.source_id=v_row.id::text
    ) then
      insert into public.user_notifications(user_id,notification_type,title,message,target_url,source_type,source_id,priority,category)
      values(v_uid,'contract','Nostra Care expiré','Ton contrat '||v_row.plan_name||' est arrivé à expiration.','/profil/garage/'||v_row.customer_vehicle_id,'warranty_expired_v164',v_row.id::text,'high','motors');
      v_count := v_count + 1;
    end if;
  end loop;

  -- Prochain entretien : date à moins de 7 jours ou kilométrage à moins de 500 km.
  for v_row in
    select distinct on (m.customer_vehicle_id)
           m.id, m.customer_vehicle_id, m.next_service_date, m.next_service_mileage,
           cv.current_mileage, cv.brand, cv.model, cv.vehicle_name
    from public.motors_vehicle_maintenance_v164 m
    join public.customer_vehicles cv on cv.id=m.customer_vehicle_id
    where m.owner_user_id=v_uid and m.deleted_at is null and m.status='completed'
      and (m.next_service_date is not null or m.next_service_mileage is not null)
    order by m.customer_vehicle_id, m.service_date desc, m.id desc
  loop
    if (
      (v_row.next_service_date is not null and v_row.next_service_date <= current_date + 7)
      or (v_row.next_service_mileage is not null and v_row.next_service_mileage - coalesce(v_row.current_mileage,0) <= 500)
    ) and not exists (
      select 1 from public.user_notifications n
      where n.user_id=v_uid and n.source_type='maintenance_due_v164' and n.source_id=v_row.id::text
    ) then
      insert into public.user_notifications(user_id,notification_type,title,message,target_url,source_type,source_id,priority,category)
      values(
        v_uid,'maintenance','Entretien Nostra à prévoir',
        'Un entretien est bientôt recommandé pour '||coalesce(nullif(btrim(concat_ws(' ',v_row.brand,v_row.model)),''),v_row.vehicle_name,'ton véhicule')||'.',
        '/profil/garage/'||v_row.customer_vehicle_id,'maintenance_due_v164',v_row.id::text,'high','motors'
      );
      v_count := v_count + 1;
    end if;
  end loop;

  return v_count;
end;
$$;

grant execute on function public.nostra_v164_refresh_my_vehicle_notifications() to authenticated;

