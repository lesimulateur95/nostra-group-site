create or replace function public.nostra_v164_is_manager()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.member_profiles mp
    where mp.user_id = auth.uid()
      and (
        lower(coalesce(to_jsonb(mp)->>'role','')) in ('manager','gerant','direction')
        or exists (
          select 1
          from jsonb_array_elements_text(coalesce(to_jsonb(mp)->'roles','[]'::jsonb)) r(value)
          where lower(r.value) in ('manager','gerant','direction')
        )
      )
  );
$$;

grant execute on function public.nostra_v164_is_manager() to authenticated;

