create or replace function public.nostra_promo_quote_v153(
  p_code text,
  p_scope text,
  p_amount numeric
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_code public.nostra_promo_codes_v153%rowtype;
  v_total_uses integer := 0;
  v_user_uses integer := 0;
  v_discount numeric(14,2) := 0;
begin
  if v_uid is null then raise exception using message='not_authenticated'; end if;
  if coalesce(btrim(p_code),'') = '' then return jsonb_build_object('valid',false,'reason','empty'); end if;
  select * into v_code from public.nostra_promo_codes_v153 where upper(code)=upper(btrim(p_code)) limit 1;
  if not found then return jsonb_build_object('valid',false,'reason','unknown'); end if;
  if not v_code.enabled then return jsonb_build_object('valid',false,'reason','disabled'); end if;
  if v_code.scope <> 'global' and v_code.scope <> p_scope then return jsonb_build_object('valid',false,'reason','scope'); end if;
  if v_code.starts_at is not null and now() < v_code.starts_at then return jsonb_build_object('valid',false,'reason','not_started'); end if;
  if v_code.ends_at is not null and now() > v_code.ends_at then return jsonb_build_object('valid',false,'reason','expired'); end if;
  if coalesce(p_amount,0) < v_code.min_amount then return jsonb_build_object('valid',false,'reason','minimum','minimum',v_code.min_amount); end if;
  select count(*) into v_total_uses from public.nostra_promo_redemptions_v153 where promo_id=v_code.id;
  select count(*) into v_user_uses from public.nostra_promo_redemptions_v153 where promo_id=v_code.id and user_id=v_uid;
  if v_code.max_uses is not null and v_total_uses >= v_code.max_uses then return jsonb_build_object('valid',false,'reason','limit'); end if;
  if v_user_uses >= v_code.max_uses_per_user then return jsonb_build_object('valid',false,'reason','user_limit'); end if;
  if v_code.discount_type='percent' then
    v_discount := round(greatest(0,p_amount) * least(100,v_code.discount_value) / 100, 2);
  else
    v_discount := least(greatest(0,p_amount),v_code.discount_value);
  end if;
  if v_code.max_discount is not null then v_discount := least(v_discount,v_code.max_discount); end if;
  return jsonb_build_object(
    'valid',true,'promo_id',v_code.id,'code',v_code.code,'label',v_code.label,
    'discount_type',v_code.discount_type,'discount_value',v_code.discount_value,
    'discount_amount',v_discount,'final_amount',greatest(0,p_amount-v_discount)
  );
end;
$$;
grant execute on function public.nostra_promo_quote_v153(text,text,numeric) to authenticated;

create or replace function public.nostra_redeem_promo_v153(
  p_code text,
  p_scope text,
  p_amount numeric,
  p_source_type text default null,
  p_source_id text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_quote jsonb;
  v_promo uuid;
begin
  v_quote := public.nostra_promo_quote_v153(p_code,p_scope,p_amount);
  if coalesce((v_quote->>'valid')::boolean,false) is false then return v_quote; end if;
  v_promo := (v_quote->>'promo_id')::uuid;
  insert into public.nostra_promo_redemptions_v153(promo_id,user_id,scope,source_type,source_id,base_amount,discount_amount)
  values(v_promo,v_uid,p_scope,p_source_type,p_source_id,p_amount,(v_quote->>'discount_amount')::numeric);
  return v_quote;
end;
$$;
grant execute on function public.nostra_redeem_promo_v153(text,text,numeric,text,text) to authenticated;

-- Wrapper de commande : conserve le moteur V93, puis applique la remise dans la même transaction.
create or replace function public.place_nostra_order_v153(
  p_order_number text,
  p_customer_name text,
  p_customer_note text default null,
  p_promo_code text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_result jsonb;
  v_order_id bigint;
  v_total numeric(14,2);
  v_quote jsonb;
  v_discount numeric(14,2) := 0;
begin
  v_result := public.place_nostra_order_v93(p_order_number,p_customer_name,p_customer_note);
  v_order_id := (v_result->>'id')::bigint;
  select total into v_total from public.orders where id=v_order_id;
  if coalesce(btrim(p_promo_code),'') <> '' then
    v_quote := public.nostra_redeem_promo_v153(p_promo_code,'motors',v_total,'order',v_order_id::text);
    if coalesce((v_quote->>'valid')::boolean,false) is false then
      raise exception using message='promo_' || coalesce(v_quote->>'reason','invalid');
    end if;
    v_discount := coalesce((v_quote->>'discount_amount')::numeric,0);
    update public.orders
      set total=greatest(0,total-v_discount),
          items=coalesce(items,'[]'::jsonb) || jsonb_build_array(jsonb_build_object(
            'item_type','discount','name','Code promo ' || upper(btrim(p_promo_code)),
            'quantity',1,'unit_price',-v_discount,'image_url',null
          )), updated_at=now()
      where id=v_order_id;
  end if;
  select total into v_total from public.orders where id=v_order_id;
  return v_result || jsonb_build_object('total',v_total,'discount',v_discount);
end;
$$;
grant execute on function public.place_nostra_order_v153(text,text,text,text) to authenticated;

