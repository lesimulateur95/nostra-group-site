create or replace function public.nostra_generate_vehicle_contract_v153(p_order_id bigint)
returns uuid
language plpgsql
security definer
set search_path=public
as $$
declare
  v_order public.orders%rowtype;
  v_progress public.order_progress_v153%rowtype;
  v_signed_at timestamptz;
  v_contract_id uuid;
  v_number text;
  v_invoice_id bigint;
begin
  select * into v_order from public.orders where id=p_order_id;
  if not found then return null; end if;
  if auth.uid() is distinct from v_order.user_id and public.nostra_role() not in ('manager','employee','commercial') then
    raise exception using message='forbidden';
  end if;
  select * into v_progress from public.order_progress_v153 where order_id=p_order_id;
  if not found or v_progress.payment_status <> 'paid' then return null; end if;

  -- Recherche d'un bon de commande signé via le registre documentaire.
  if to_regclass('public.nostra_document_registry') is not null then
    select r.signed_at into v_signed_at
    from public.nostra_document_registry r
    join public.invoices i on (
      (r.source_table='invoices' and r.source_id=i.id::text)
      or (r.metadata->>'invoice_id'=i.id::text)
    )
    where i.order_id=p_order_id
      and i.document_type='order_form'
      and r.signature_status='signed'
    order by r.signed_at desc nulls last limit 1;
  end if;
  if v_signed_at is null then return null; end if;

  select id into v_contract_id from public.nostra_vehicle_contracts_v153 where order_id=p_order_id;
  if v_contract_id is not null then return v_contract_id; end if;
  v_number := 'NM-CTR-' || to_char(now(),'YYYYMMDD') || '-' || lpad(p_order_id::text,6,'0');
  insert into public.nostra_vehicle_contracts_v153(order_id,user_id,contract_number,customer_name,amount,vehicle_snapshot,signed_at,paid_at)
  values(p_order_id,v_order.user_id,v_number,coalesce(nullif(v_order.customer_name,''),'Client Nostra Motors'),v_order.total,coalesce(v_order.items,'[]'::jsonb),v_signed_at,now())
  returning id into v_contract_id;

  -- Ajoute un document au centre documentaire lorsqu'il existe.
  if to_regclass('public.invoices') is not null then
    insert into public.invoices(user_id,invoice_number,status,amount,issued_at,download_url,order_id,document_type,document_title,document_payload)
    values(v_order.user_id,v_number,'issued',v_order.total,now(),'/profil/contrats/'||v_contract_id::text,p_order_id,'contract','Contrat de vente Nostra Motors',jsonb_build_object('contract_id',v_contract_id,'order_number',v_order.order_number,'signed_at',v_signed_at,'paid_at',now()))
    on conflict(invoice_number) do update set download_url=excluded.download_url,document_payload=excluded.document_payload
    returning id into v_invoice_id;
  end if;

  if to_regclass('public.user_notifications') is not null then
    insert into public.user_notifications(user_id,notification_type,title,message,target_url,source_type,source_id,priority,category)
    values(v_order.user_id,'contract','Votre contrat de vente est disponible','La signature et le paiement ont été validés. Votre contrat définitif Nostra Motors a été généré.','/profil/contrats/'||v_contract_id::text,'vehicle_contract',v_contract_id::text,'high','motors');
  end if;
  return v_contract_id;
end;
$$;
grant execute on function public.nostra_generate_vehicle_contract_v153(bigint) to authenticated;

