create or replace function public.sync_order_commission_v137()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_settings public.commercial_commission_settings_v137%rowtype;
  v_amount numeric(14,2);
begin
  if new.status = 'completed' and new.commercial_user_id is not null then
    select * into v_settings from public.commercial_commission_settings_v137 where id = 1;
    if coalesce(v_settings.enabled, false) then
      v_amount := case
        when v_settings.commission_mode = 'fixed' then v_settings.commission_value
        else round(greatest(0, coalesce(new.total,0)) * v_settings.commission_value / 100, 2)
      end;

      insert into public.commercial_commissions_v137 (
        order_id, order_number, commercial_user_id, commercial_name, sale_amount,
        commission_mode, commission_value, commission_amount, status, sale_date, updated_at
      ) values (
        new.id, new.order_number, new.commercial_user_id,
        coalesce(nullif(new.commercial_name,''),'Commercial'), greatest(0,coalesce(new.total,0)),
        v_settings.commission_mode, v_settings.commission_value, greatest(0,v_amount),
        'pending', current_date, now()
      )
      on conflict (order_id) do update set
        commercial_user_id = excluded.commercial_user_id,
        commercial_name = excluded.commercial_name,
        sale_amount = excluded.sale_amount,
        commission_mode = case when public.commercial_commissions_v137.status = 'paid' then public.commercial_commissions_v137.commission_mode else excluded.commission_mode end,
        commission_value = case when public.commercial_commissions_v137.status = 'paid' then public.commercial_commissions_v137.commission_value else excluded.commission_value end,
        commission_amount = case when public.commercial_commissions_v137.status = 'paid' then public.commercial_commissions_v137.commission_amount else excluded.commission_amount end,
        status = case when public.commercial_commissions_v137.status = 'paid' then 'paid' else 'pending' end,
        updated_at = now();
    end if;
  elsif new.status = 'cancelled' or (old.status = 'completed' and new.status <> 'completed') then
    update public.commercial_commissions_v137
    set status = 'cancelled', updated_at = now()
    where order_id = new.id and status <> 'paid';
  end if;
  return new;
end;
$$;

drop trigger if exists sync_order_commission_v137 on public.orders;
create trigger sync_order_commission_v137
after insert or update of status, total, commercial_user_id, commercial_name on public.orders
for each row execute function public.sync_order_commission_v137();

create or replace function public.assign_order_commercial_v137(
  p_order_id bigint,
  p_commercial_user_id uuid
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare v_name text;
begin
  if not public.nostra_v137_has_any_role(array['manager']) then
    raise exception using message = 'manager_required';
  end if;

  if p_commercial_user_id is null then
    update public.orders set commercial_user_id = null, commercial_name = null where id = p_order_id;
    return;
  end if;

  select nullif(btrim(concat_ws(' ', rp_first_name, rp_last_name)),'')
  into v_name from public.member_profiles where user_id = p_commercial_user_id;
  if v_name is null then
    select coalesce(discord_name, email, 'Commercial') into v_name
    from public.member_profiles where user_id = p_commercial_user_id;
  end if;
  if v_name is null then raise exception using message = 'commercial_not_found'; end if;

  update public.orders
  set commercial_user_id = p_commercial_user_id, commercial_name = v_name
  where id = p_order_id;
end;
$$;

create or replace function public.pay_commercial_month_v137(
  p_commercial_user_id uuid,
  p_month date
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_month date := date_trunc('month', p_month)::date;
  v_name text;
  v_commission numeric(14,2) := 0;
  v_revenue numeric(14,2) := 0;
  v_sales integer := 0;
  v_bonus numeric(14,2) := 0;
  v_total numeric(14,2) := 0;
  v_payment_id bigint;
  v_accounting_id bigint;
  v_objective public.commercial_objectives_v137%rowtype;
begin
  if not public.nostra_v137_has_any_role(array['manager']) then
    raise exception using message = 'manager_required';
  end if;

  if exists (select 1 from public.commercial_payments_v137 where commercial_user_id=p_commercial_user_id and payment_month=v_month) then
    raise exception using message = 'month_already_paid';
  end if;

  select coalesce(max(commercial_name),'Commercial'), coalesce(sum(commission_amount),0),
         coalesce(sum(sale_amount),0), count(*)::integer
  into v_name, v_commission, v_revenue, v_sales
  from public.commercial_commissions_v137
  where commercial_user_id=p_commercial_user_id
    and sale_date >= v_month and sale_date < (v_month + interval '1 month')::date
    and status in ('pending','approved');

  select * into v_objective from public.commercial_objectives_v137
  where commercial_user_id=p_commercial_user_id and objective_month=v_month;

  if found and v_sales >= v_objective.sales_target and v_revenue >= v_objective.revenue_target then
    v_bonus := v_objective.target_bonus;
  end if;
  v_total := v_commission + v_bonus;
  if v_total <= 0 then raise exception using message = 'nothing_to_pay'; end if;

  insert into public.accounting_entries(entry_date,entry_type,category,label,amount,notes)
  values(current_date,'expense','Commissions commerciales','Commissions ' || v_name || ' — ' || to_char(v_month,'MM/YYYY'),v_total,
    'Commissions : ' || v_commission || ' € · Bonus objectif : ' || v_bonus || ' €')
  returning id into v_accounting_id;

  insert into public.commercial_payments_v137(
    commercial_user_id,commercial_name,payment_month,commission_total,objective_bonus,total_paid,accounting_entry_id,paid_by
  ) values(p_commercial_user_id,v_name,v_month,v_commission,v_bonus,v_total,v_accounting_id,auth.uid())
  returning id into v_payment_id;

  update public.commercial_commissions_v137 set status='paid',paid_at=now(),payment_id=v_payment_id,updated_at=now()
  where commercial_user_id=p_commercial_user_id and sale_date >= v_month
    and sale_date < (v_month + interval '1 month')::date and status in ('pending','approved');
  update public.commercial_objectives_v137 set paid_at=now(),updated_at=now()
  where commercial_user_id=p_commercial_user_id and objective_month=v_month;

  return jsonb_build_object('payment_id',v_payment_id,'commission',v_commission,'bonus',v_bonus,'total',v_total);
end;
$$;

