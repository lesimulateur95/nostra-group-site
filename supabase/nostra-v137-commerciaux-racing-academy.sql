create or replace function public.nostra_v137_has_any_role(p_roles text[])
returns boolean
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_profile jsonb := '{}'::jsonb;
  v_claims jsonb := coalesce(auth.jwt(), '{}'::jsonb);
  v_role_text text := '';
begin
  if auth.uid() is null then return false; end if;

  select to_jsonb(profile) into v_profile
  from public.member_profiles profile
  where profile.user_id = auth.uid()
  limit 1;

  v_role_text := lower(
    coalesce(v_profile->>'role','') || ' ' ||
    coalesce(v_profile->>'roles','') || ' ' ||
    coalesce(v_claims->>'role','') || ' ' ||
    coalesce(v_claims->'app_metadata'->>'role','') || ' ' ||
    coalesce(v_claims->'app_metadata'->>'roles','') || ' ' ||
    coalesce(v_claims->'user_metadata'->>'role','') || ' ' ||
    coalesce(v_claims->'user_metadata'->>'roles','')
  );

  if coalesce(v_profile->>'discord_id','') = '331843410962939908' then
    return 'manager' = any(p_roles);
  end if;

  return exists (
    select 1 from unnest(p_roles) wanted
    where v_role_text like '%' || lower(wanted) || '%'
       or (wanted = 'manager' and v_role_text ~ '(gerant|gérant|direction|administrator|admin)')
       or (wanted = 'commissioner' and v_role_text ~ '(commissaire|steward)')
       or (wanted = 'commercial' and v_role_text ~ '(commercial|vendeur)')
       or (wanted = 'employee' and v_role_text ~ '(employe|employé|staff)')
  );
end;
$$;

revoke all on function public.nostra_v137_has_any_role(text[]) from public, anon;
grant execute on function public.nostra_v137_has_any_role(text[]) to authenticated;

