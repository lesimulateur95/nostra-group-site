create or replace function public.issue_academy_qualification_v137()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare v_course public.academy_courses_v137%rowtype;
begin
  if new.status <> 'passed' then return new; end if;
  select * into v_course from public.academy_courses_v137 where id=new.course_id;
  if new.theory_score is null or new.practical_score is null
     or new.theory_score < v_course.theory_pass_score
     or new.practical_score < v_course.practical_pass_score then
    raise exception using message='passing_scores_required';
  end if;

  insert into public.academy_qualifications_v137(
    qualification_number,enrollment_id,course_id,user_id,holder_name,qualification_label,theory_score,practical_score
  ) values(
    'NRA-' || to_char(current_date,'YYYY') || '-' || lpad(new.id::text,6,'0'),
    new.id,new.course_id,new.user_id,new.applicant_name,v_course.qualification_label,new.theory_score,new.practical_score
  ) on conflict (enrollment_id) do update set
    holder_name=excluded.holder_name,qualification_label=excluded.qualification_label,
    theory_score=excluded.theory_score,practical_score=excluded.practical_score,active=true;

  new.completed_at := coalesce(new.completed_at,now());
  return new;
end;
$$;

