create or replace function public.nostra_v142_delete_licence_permanently(
  p_licence_id text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.nostra_v137_has_any_role(array['manager']) then
    raise exception using message = 'manager_required';
  end if;

  if not exists (
    select 1 from public.nostra_licences l where l.id::text = p_licence_id
  ) then
    raise exception using message = 'licence_not_found';
  end if;

  -- On ne met PAS le drapeau de réémission : le trigger DELETE conserve la
  -- trace et interdit toute réparation automatique ultérieure.
  if to_regprocedure('public.delete_nostra_licence(text)') is not null then
    execute 'select public.delete_nostra_licence($1::text)' using p_licence_id;
  elsif to_regprocedure('public.delete_nostra_licence(uuid)') is not null then
    execute 'select public.delete_nostra_licence($1::uuid)' using p_licence_id;
  else
    delete from public.nostra_licences where id::text = p_licence_id;
  end if;
end;
$$;

revoke all on function public.nostra_v142_delete_licence_permanently(text) from public;
grant execute on function public.nostra_v142_delete_licence_permanently(text) to authenticated;

