create or replace function public.nostra_v142_before_official_licence_insert()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_code text;
  v_allow boolean := coalesce(current_setting('nostra.allow_licence_reissue', true), '') = 'on';
  v_deleted_id bigint;
begin
  v_code := public.nostra_v140_license_code_from_name(new.licence_name);

  select d.id into v_deleted_id
  from public.nostra_deleted_licences_v142 d
  where d.holder_user_id = new.holder_user_id
    and (
      (v_code is not null and public.nostra_v140_normalize(d.license_code) = public.nostra_v140_normalize(v_code))
      or (
        v_code is null
        and public.nostra_v140_normalize(d.licence_name) = public.nostra_v140_normalize(new.licence_name)
      )
    )
  order by d.deleted_at desc
  limit 1;

  if v_deleted_id is not null and not v_allow then
    raise exception using
      message = 'licence_deleted_no_auto_reissue',
      hint = 'La licence a été supprimée par la Direction et ne peut pas être recréée par une ancienne synchronisation.';
  end if;

  if v_deleted_id is not null and v_allow then
    delete from public.nostra_deleted_licences_v142 d
    where d.holder_user_id = new.holder_user_id
      and (
        (v_code is not null and public.nostra_v140_normalize(d.license_code) = public.nostra_v140_normalize(v_code))
        or (
          v_code is null
          and public.nostra_v140_normalize(d.licence_name) = public.nostra_v140_normalize(new.licence_name)
        )
      );
  end if;

  return new;
end;
$$;

create or replace function public.nostra_v142_after_official_licence_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_code text;
begin
  if tg_op = 'DELETE' then
    v_code := public.nostra_v142_official_licence_code(old.id::text, old.licence_name);

    insert into public.nostra_deleted_licences_v142(
      deleted_licence_id, holder_user_id, license_code, licence_name,
      licence_number, deleted_by, deleted_at
    ) values (
      old.id::text, old.holder_user_id, v_code, old.licence_name,
      old.licence_number, auth.uid(), now()
    );

    delete from public.academy_generated_licence_links_v142
    where licence_id = old.id::text;

    if to_regclass('public.academy_licence_controls_v140') is not null then
      delete from public.academy_licence_controls_v140
      where licence_id = old.id::text;
    end if;

    return old;
  end if;

  -- INSERT / UPDATE : toute licence officielle reconnue est liée à l'Academy.
  v_code := public.nostra_v140_license_code_from_name(new.licence_name);
  if v_code is not null then
    insert into public.academy_generated_licence_links_v142(
      licence_id, holder_user_id, license_code, licence_name, source, updated_at
    ) values (
      new.id::text, new.holder_user_id, v_code, new.licence_name, 'auto', now()
    )
    on conflict (licence_id) do update set
      holder_user_id = excluded.holder_user_id,
      licence_name = excluded.licence_name,
      license_code = case
        when public.academy_generated_licence_links_v142.source = 'generator-explicit'
          then public.academy_generated_licence_links_v142.license_code
        else excluded.license_code
      end,
      source = case
        when public.academy_generated_licence_links_v142.source = 'generator-explicit'
          then public.academy_generated_licence_links_v142.source
        else excluded.source
      end,
      updated_at = now();
  end if;

  return new;
end;
$$;

drop trigger if exists nostra_v142_before_licence_insert on public.nostra_licences;
create trigger nostra_v142_before_licence_insert
before insert on public.nostra_licences
for each row execute function public.nostra_v142_before_official_licence_insert();

drop trigger if exists nostra_v142_after_licence_insert_update on public.nostra_licences;
create trigger nostra_v142_after_licence_insert_update
after insert or update of holder_user_id, licence_name on public.nostra_licences
for each row execute function public.nostra_v142_after_official_licence_change();

drop trigger if exists nostra_v142_after_licence_delete on public.nostra_licences;
create trigger nostra_v142_after_licence_delete
after delete on public.nostra_licences
for each row execute function public.nostra_v142_after_official_licence_change();

-- Backfill des licences déjà présentes au moment de la migration.
insert into public.academy_generated_licence_links_v142(
  licence_id, holder_user_id, license_code, licence_name, source
)
select
  l.id::text,
  l.holder_user_id,
  public.nostra_v140_license_code_from_name(l.licence_name),
  l.licence_name,
  'backfill'
from public.nostra_licences l
where l.holder_user_id is not null
  and public.nostra_v140_license_code_from_name(l.licence_name) is not null
on conflict (licence_id) do nothing;

