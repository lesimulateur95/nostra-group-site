create table if not exists public.academy_generated_licence_links_v142 (
  licence_id text primary key,
  holder_user_id uuid not null references auth.users(id) on delete cascade,
  license_code text not null,
  licence_name text,
  source text not null default 'auto',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists academy_generated_licence_links_v142_holder_idx
  on public.academy_generated_licence_links_v142(holder_user_id, license_code);

alter table public.academy_generated_licence_links_v142 enable row level security;

drop policy if exists "academy generated licence links read v142"
  on public.academy_generated_licence_links_v142;
create policy "academy generated licence links read v142"
on public.academy_generated_licence_links_v142
for select to authenticated
using (
  holder_user_id = auth.uid()
  or public.nostra_v137_has_any_role(array['manager','commissioner'])
);

drop policy if exists "academy generated licence links manage v142"
  on public.academy_generated_licence_links_v142;
create policy "academy generated licence links manage v142"
on public.academy_generated_licence_links_v142
for all to authenticated
using (public.nostra_v137_has_any_role(array['manager','commissioner']))
with check (public.nostra_v137_has_any_role(array['manager','commissioner']));

grant select,insert,update,delete on public.academy_generated_licence_links_v142 to authenticated;

create or replace function public.nostra_v142_official_licence_code(
  p_licence_id text,
  p_licence_name text
)
returns text
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_code text;
begin
  select l.license_code into v_code
  from public.academy_generated_licence_links_v142 l
  where l.licence_id = p_licence_id
  limit 1;

  if nullif(trim(coalesce(v_code,'')), '') is not null then
    return v_code;
  end if;

  return public.nostra_v140_license_code_from_name(p_licence_name);
end;
$$;

revoke all on function public.nostra_v142_official_licence_code(text,text) from public;
grant execute on function public.nostra_v142_official_licence_code(text,text) to authenticated;

create or replace function public.nostra_v142_link_official_licence(
  p_licence_id text,
  p_holder_user_id uuid,
  p_licence_name text,
  p_license_code text default null,
  p_source text default 'auto'
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_code text;
begin
  if auth.uid() is null then
    raise exception using message = 'authentication_required';
  end if;

  if p_holder_user_id <> auth.uid()
     and not public.nostra_v137_has_any_role(array['manager','commissioner']) then
    raise exception using message = 'academy_staff_required';
  end if;

  if nullif(trim(coalesce(p_license_code,'')), '') is not null then
    select t.code into v_code
    from public.pilot_license_types t
    where public.nostra_v140_normalize(t.code) = public.nostra_v140_normalize(p_license_code)
    limit 1;

    if v_code is null then
      raise exception using message = 'academy_license_code_invalid';
    end if;
  else
    v_code := public.nostra_v140_license_code_from_name(p_licence_name);
  end if;

  if v_code is null then
    return null;
  end if;

  insert into public.academy_generated_licence_links_v142(
    licence_id, holder_user_id, license_code, licence_name, source, updated_at
  ) values (
    p_licence_id, p_holder_user_id, v_code, p_licence_name,
    coalesce(nullif(trim(p_source),''),'auto'), now()
  )
  on conflict (licence_id) do update set
    holder_user_id = excluded.holder_user_id,
    license_code = excluded.license_code,
    licence_name = excluded.licence_name,
    source = excluded.source,
    updated_at = now();

  return v_code;
end;
$$;

revoke all on function public.nostra_v142_link_official_licence(text,uuid,text,text,text) from public;
grant execute on function public.nostra_v142_link_official_licence(text,uuid,text,text,text) to authenticated;

