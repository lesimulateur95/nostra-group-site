-- 3. GENERATEUR DIRECTION : DELIVRANCE + LIAISON ACADEMY EN UNE ACTION
-- ---------------------------------------------------------------------------

create or replace function public.issue_nostra_licence_academy_v142(
  p_holder_user_id uuid,
  p_licence_name text,
  p_category text,
  p_authority text,
  p_valid_from date,
  p_valid_until date,
  p_permissions text,
  p_notes text,
  p_send_to_citizen boolean,
  p_academy_license_code text default null
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_result text;
begin
  if not public.nostra_v137_has_any_role(array['manager']) then
    raise exception using message = 'manager_required';
  end if;

  -- Une délivrance volontaire Direction est autorisée à recréer une licence
  -- précédemment supprimée. Les anciennes synchronisations automatiques, non.
  perform set_config('nostra.allow_licence_reissue', 'on', true);

  select public.issue_nostra_licence_safe_v74(
    p_holder_user_id,
    p_licence_name,
    p_category,
    p_authority,
    p_valid_from,
    p_valid_until,
    p_permissions,
    p_notes,
    p_send_to_citizen
  ) into v_result;

  perform public.nostra_v142_link_official_licence(
    v_result,
    p_holder_user_id,
    p_licence_name,
    p_academy_license_code,
    case when nullif(trim(coalesce(p_academy_license_code,'')), '') is null
      then 'generator-auto'
      else 'generator-explicit'
    end
  );

  return v_result;
end;
$$;

revoke all on function public.issue_nostra_licence_academy_v142(
  uuid,text,text,text,date,date,text,text,boolean,text
) from public;
grant execute on function public.issue_nostra_licence_academy_v142(
  uuid,text,text,text,date,date,text,text,boolean,text
) to authenticated;

