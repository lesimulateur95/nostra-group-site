create or replace function public.nostra_convert_my_holds_v161(p_order_id bigint)
returns integer
language plpgsql
security definer
set search_path=public
as $$
declare
  v_uid uuid:=auth.uid();
  v_count integer;
begin
  if v_uid is null then raise exception using message='not_authenticated'; end if;
  if not exists(select 1 from public.orders where id=p_order_id and user_id=v_uid) then
    raise exception using message='order_not_found';
  end if;

  update public.nostra_vehicle_holds_v161 h
  set status='converted',order_id=p_order_id,updated_at=now()
  where h.user_id=v_uid
    and h.status='active'
    and exists (
      select 1
      from jsonb_array_elements(coalesce((select items from public.orders where id=p_order_id),'[]'::jsonb)) item
      where coalesce(item->>'item_type','')='vehicle'
        and coalesce(item->>'vehicle_id','')<>''
        and (item->>'vehicle_id')::bigint=h.vehicle_id
    );
  get diagnostics v_count = row_count;
  return v_count;
end;
$$;
revoke all on function public.nostra_convert_my_holds_v161(bigint) from public, anon;
grant execute on function public.nostra_convert_my_holds_v161(bigint) to authenticated;

-- Conversion transactionnelle : dès que la commande contenant les VL est créée,
-- les blocages correspondants deviennent historiques. Si la création de commande
-- est annulée par PostgreSQL, cette conversion est elle aussi annulée.
create or replace function public.nostra_convert_matching_holds_after_order_v161()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
begin
  update public.nostra_vehicle_holds_v161 h
  set status='converted',order_id=new.id,updated_at=now()
  where h.user_id=new.user_id
    and h.status='active'
    and exists (
      select 1
      from jsonb_array_elements(coalesce(new.items,'[]'::jsonb)) item
      where coalesce(item->>'item_type','')='vehicle'
        and coalesce(item->>'vehicle_id','')<>''
        and (item->>'vehicle_id')::bigint=h.vehicle_id
    );
  return new;
end;
$$;

drop trigger if exists trg_nostra_convert_matching_holds_v161 on public.orders;
create trigger trg_nostra_convert_matching_holds_v161
after insert on public.orders
for each row execute function public.nostra_convert_matching_holds_after_order_v161();
revoke all on function public.nostra_convert_matching_holds_after_order_v161() from public, anon;

create or replace function public.nostra_active_vehicle_holds_admin_v161()
returns table(
  id bigint,
  user_id uuid,
  vehicle_id bigint,
  vehicle_name text,
  quantity integer,
  expires_at timestamptz,
  customer_name text
)
language plpgsql
security definer
set search_path=public
as $$
begin
  if not public.nostra_can_manage_vehicle_reservations_v93() then raise exception using message='forbidden'; end if;
  perform public.nostra_cleanup_expired_holds_v161();
  return query
  select
    h.id,
    h.user_id,
    h.vehicle_id,
    btrim(coalesce(cv.brand,'') || ' ' || coalesce(cv.model,'')) as vehicle_name,
    h.quantity,
    h.expires_at,
    coalesce(
      nullif(btrim(concat_ws(' ',mp.rp_first_name,mp.rp_last_name)),''),
      nullif(mp.discord_name,''),
      'Citoyen Nostra'
    ) as customer_name
  from public.nostra_vehicle_holds_v161 h
  join public.catalog_vehicles cv on cv.id=h.vehicle_id
  left join public.member_profiles mp on mp.user_id=h.user_id
  where h.status='active' and h.expires_at>now()
  order by h.expires_at asc,h.id asc;
end;
$$;

create or replace function public.nostra_admin_release_hold_v161(p_hold_id bigint)
returns void
language plpgsql
security definer
set search_path=public
as $$
declare v_hold public.nostra_vehicle_holds_v161%rowtype;
begin
  if not public.nostra_can_manage_vehicle_reservations_v93() then raise exception using message='forbidden'; end if;
  select * into v_hold from public.nostra_vehicle_holds_v161 where id=p_hold_id and status='active' for update;
  if not found then return; end if;
  update public.nostra_vehicle_holds_v161 set status='released',updated_at=now() where id=p_hold_id;
  delete from public.cart_items
  where user_id=v_hold.user_id
    and ((item_type='vehicle' and vehicle_id=v_hold.vehicle_id) or (item_type='delivery' and related_vehicle_id=v_hold.vehicle_id));
end;
$$;

