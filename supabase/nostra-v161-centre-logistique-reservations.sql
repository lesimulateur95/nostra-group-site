create or replace function public.nostra_cleanup_expired_holds_v161()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_hold record;
  v_count integer := 0;
begin
  for v_hold in
    select id, user_id, vehicle_id
    from public.nostra_vehicle_holds_v161
    where status = 'active' and expires_at <= now()
    order by id
    for update skip locked
  loop
    update public.nostra_vehicle_holds_v161
    set status = 'expired', updated_at = now()
    where id = v_hold.id and status = 'active';

    if found then
      delete from public.cart_items
      where user_id = v_hold.user_id
        and (
          (item_type = 'vehicle' and vehicle_id = v_hold.vehicle_id)
          or (item_type = 'delivery' and related_vehicle_id = v_hold.vehicle_id)
        );
      v_count := v_count + 1;
    end if;
  end loop;
  return v_count;
end;
$$;

revoke all on function public.nostra_cleanup_expired_holds_v161() from public, anon;
grant execute on function public.nostra_cleanup_expired_holds_v161() to authenticated;

create or replace function public.nostra_vehicle_hold_counts_v161(p_vehicle_ids bigint[])
returns table(vehicle_id bigint, reserved_quantity integer)
language plpgsql
security definer
set search_path = public
as $$
begin
  perform public.nostra_cleanup_expired_holds_v161();
  return query
  select h.vehicle_id, coalesce(sum(h.quantity),0)::integer
  from public.nostra_vehicle_holds_v161 h
  where h.status = 'active'
    and h.expires_at > now()
    and h.vehicle_id = any(coalesce(p_vehicle_ids, array[]::bigint[]))
  group by h.vehicle_id;
end;
$$;

