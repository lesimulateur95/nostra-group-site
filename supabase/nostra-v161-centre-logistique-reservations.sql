create or replace function public.nostra_attach_delivery_snapshot_v161(
  p_order_id bigint,
  p_address_id bigint default null,
  p_label text default null,
  p_address text default null,
  p_phone text default null,
  p_instructions text default null
)
returns void
language plpgsql
security definer
set search_path=public
as $$
declare
  v_uid uuid:=auth.uid();
  v_addr public.nostra_delivery_addresses_v161%rowtype;
  v_label text:=nullif(btrim(coalesce(p_label,'')),'');
  v_address text:=nullif(btrim(coalesce(p_address,'')),'');
  v_phone text:=nullif(btrim(coalesce(p_phone,'')),'');
  v_instructions text:=nullif(btrim(coalesce(p_instructions,'')),'');
  v_address_id bigint:=null;
begin
  if v_uid is null then raise exception using message='not_authenticated'; end if;
  if not exists(select 1 from public.orders where id=p_order_id and user_id=v_uid) then
    raise exception using message='order_not_found';
  end if;
  if p_address_id is not null then
    select * into v_addr from public.nostra_delivery_addresses_v161
    where id=p_address_id and user_id=v_uid;
    if found then
      v_address_id:=v_addr.id;
      v_label:=v_addr.label;
      v_address:=btrim(concat_ws(', ',v_addr.address_line,nullif(v_addr.city,''),nullif(v_addr.zone,'')));
      v_phone:=coalesce(nullif(v_addr.phone,''),v_phone);
      v_instructions:=coalesce(nullif(v_addr.instructions,''),v_instructions);
    end if;
  end if;
  update public.orders set
    delivery_address_id=v_address_id,
    delivery_address_label=v_label,
    delivery_address=v_address,
    delivery_phone=v_phone,
    delivery_instructions=v_instructions,
    delivery_stage=case when v_address is null then delivery_stage else 'awaiting_planning' end,
    updated_at=now()
  where id=p_order_id and user_id=v_uid;
end;
$$;
