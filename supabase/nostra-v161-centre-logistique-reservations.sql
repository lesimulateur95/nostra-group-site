create or replace function public.nostra_upsert_delivery_fleet_v161(
  p_id bigint default null,
  p_name text default null,
  p_type text default 'custom',
  p_capacity integer default 1,
  p_enabled boolean default true,
  p_status text default 'available',
  p_display_order integer default 0
)
returns bigint
language plpgsql
security definer
set search_path=public
as $$
declare v_id bigint;
begin
  if not public.nostra_can_manage_vehicle_reservations_v93() then raise exception using message='forbidden'; end if;
  if length(btrim(coalesce(p_name,'')))<2 or p_capacity<1 or p_capacity>50 then raise exception using message='invalid_fleet'; end if;
  if p_type not in ('plateau','semi','carrier','custom') or p_status not in ('available','maintenance','inactive') then raise exception using message='invalid_fleet'; end if;
  if p_id is null then
    insert into public.nostra_delivery_fleet_v161(name,fleet_type,capacity,enabled,status,display_order)
