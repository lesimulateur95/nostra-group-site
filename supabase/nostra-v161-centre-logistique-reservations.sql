create or replace function public.nostra_validate_my_cart_holds_v161()
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  v_uid uuid:=auth.uid();
  v_line record;
  v_hold record;
begin
  if v_uid is null then raise exception using message='not_authenticated'; end if;
  perform public.nostra_cleanup_expired_holds_v161();
  for v_line in
    select ci.vehicle_id,sum(greatest(ci.quantity,1))::integer quantity
    from public.cart_items ci
    join public.catalog_vehicles cv on cv.id=ci.vehicle_id
    where ci.user_id=v_uid and ci.item_type='vehicle' and ci.vehicle_id is not null
      and coalesce(cv.catalog_type,'standard')<>'concession'
    group by ci.vehicle_id
  loop
    select * into v_hold from public.nostra_vehicle_holds_v161
    where user_id=v_uid and vehicle_id=v_line.vehicle_id and status='active' and expires_at>now()
    order by id desc limit 1;
    if not found or v_hold.quantity < v_line.quantity then
      raise exception using message='hold_expired';
    end if;
  end loop;
  return jsonb_build_object('valid',true);
end;
$$;
