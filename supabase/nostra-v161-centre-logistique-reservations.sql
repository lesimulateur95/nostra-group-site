create or replace function public.nostra_sync_delivery_checklist_v161(p_order_id bigint)
returns void
language plpgsql
security definer
set search_path=public
as $$
declare
  v_item jsonb;
  v_items jsonb := coalesce((select items from public.orders where id=p_order_id),'[]'::jsonb);
begin
  if not public.nostra_can_manage_vehicle_reservations_v93() then
    raise exception using message='forbidden';
  end if;

  -- La checklist contient uniquement les VL réellement livrés à domicile.
  -- Les poids lourds / retraits showroom éventuellement présents dans la même
  -- commande ne doivent pas apparaître dans le chargement du porte-véhicules.
  for v_item in
    select vehicle.value
    from jsonb_array_elements(v_items) as vehicle(value)
    where coalesce(vehicle.value->>'item_type','')='vehicle'
      and coalesce(vehicle.value->>'vehicle_id','')<>''
      and exists (
        select 1
        from jsonb_array_elements(v_items) as delivery(value)
        where coalesce(delivery.value->>'item_type','')='delivery'
          and delivery.value->>'related_vehicle_id'=vehicle.value->>'vehicle_id'
      )
  loop
    insert into public.nostra_delivery_checklist_v161(order_id,vehicle_id,vehicle_name,quantity)
    values(
      p_order_id,
      (v_item->>'vehicle_id')::bigint,
      coalesce(nullif(v_item->>'name',''),'Véhicule'),
      greatest(1,coalesce((v_item->>'quantity')::integer,1))
    )
    on conflict(order_id,vehicle_id) do update set
      vehicle_name=excluded.vehicle_name,
      quantity=excluded.quantity,
      prepared_quantity=least(public.nostra_delivery_checklist_v161.prepared_quantity,excluded.quantity),
      loaded_quantity=least(public.nostra_delivery_checklist_v161.loaded_quantity,excluded.quantity),
      updated_at=now();
  end loop;
end;
$$;

create or replace function public.nostra_update_delivery_plan_v161(
  p_order_id bigint,
  p_stage text,
  p_start timestamptz default null,
  p_end timestamptz default null,
  p_driver text default null,
  p_notes text default null,
  p_fleet_ids bigint[] default array[]::bigint[]
)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  v_required integer:=0;
  v_capacity integer:=0;
  v_conflicts integer:=0;
  v_delivery_status text:='not_planned';
  v_assignment_status text:='planned';
  v_end timestamptz:=p_end;
  v_slot_minutes integer:=60;
begin
  if not public.nostra_can_manage_vehicle_reservations_v93() then raise exception using message='forbidden'; end if;
  if p_stage not in ('awaiting_planning','planned','preparing','loading','departed','in_transit','delivered','closed','cancelled') then
    raise exception using message='invalid_delivery_stage';
  end if;
  if not exists(select 1 from public.orders where id=p_order_id) then raise exception using message='order_not_found'; end if;

  select coalesce(sum(greatest(1,coalesce((x->>'quantity')::integer,1))),0)::integer into v_required
  from jsonb_array_elements(coalesce((select items from public.orders where id=p_order_id),'[]'::jsonb)) x
  where coalesce(x->>'item_type','')='delivery';

  if p_stage not in ('awaiting_planning','cancelled') then
    if p_start is null then raise exception using message='invalid_delivery_date'; end if;
    if v_end is null then
      select default_slot_minutes into v_slot_minutes
      from public.nostra_logistics_settings_v161 where singleton=true;
      v_slot_minutes:=coalesce(v_slot_minutes,60);
      v_end:=p_start + make_interval(mins => v_slot_minutes);
    end if;
    if v_end<=p_start then raise exception using message='invalid_delivery_date'; end if;
    if coalesce(array_length(p_fleet_ids,1),0)=0 then raise exception using message='fleet_required'; end if;

    select coalesce(sum(capacity),0)::integer into v_capacity
    from public.nostra_delivery_fleet_v161
    where id=any(p_fleet_ids) and enabled=true and status='available';
    if v_capacity < v_required then raise exception using message='fleet_capacity_insufficient'; end if;

    select count(*)::integer into v_conflicts
    from public.nostra_delivery_assignments_v161 a
    join public.nostra_delivery_fleet_v161 f on f.id=a.fleet_id
    where a.fleet_id=any(p_fleet_ids)
      and a.order_id<>p_order_id
      and a.status not in ('completed','cancelled')
      and tstzrange(a.scheduled_start,a.scheduled_end,'[)') && tstzrange(p_start,v_end,'[)');
    if v_conflicts>0 then raise exception using message='fleet_conflict'; end if;
  end if;

  v_delivery_status := case
    when p_stage='awaiting_planning' then 'not_planned'
    when p_stage in ('planned','preparing','loading') then 'planned'
    when p_stage in ('departed','in_transit') then 'in_progress'
    when p_stage in ('delivered','closed') then 'delivered'
    when p_stage='cancelled' then 'cancelled'
    else 'not_planned' end;
  v_assignment_status := case
    when p_stage='loading' then 'loading'
    when p_stage in ('departed','in_transit') then 'in_transit'
    when p_stage in ('delivered','closed') then 'completed'
    when p_stage='cancelled' then 'cancelled'
    else 'planned' end;

  update public.orders set
    delivery_stage=p_stage,
    delivery_status=v_delivery_status,
    delivery_date=p_start,
    delivery_window_end=v_end,
    delivery_driver=nullif(btrim(coalesce(p_driver,'')),''),
    delivery_notes=nullif(btrim(coalesce(p_notes,'')),''),
    updated_at=now()
  where id=p_order_id;

  delete from public.nostra_delivery_assignments_v161 where order_id=p_order_id;
  if p_stage not in ('awaiting_planning','cancelled') then
    insert into public.nostra_delivery_assignments_v161(order_id,fleet_id,scheduled_start,scheduled_end,status)
    select p_order_id,id,p_start,v_end,v_assignment_status
    from public.nostra_delivery_fleet_v161
    where id=any(p_fleet_ids);
  end if;

  perform public.nostra_sync_delivery_checklist_v161(p_order_id);
  return jsonb_build_object('required_capacity',v_required,'assigned_capacity',v_capacity,'stage',p_stage);
end;
$$;

create or replace function public.nostra_update_delivery_checklist_v161(
  p_order_id bigint,
  p_vehicle_id bigint,
  p_prepared integer,
  p_loaded integer
