create or replace function public.nostra_refresh_my_cart_holds_v161()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_hold_minutes integer := 20;
  v_max integer := 10;
  v_total integer := 0;
  v_line record;
  v_other integer;
  v_existing_id bigint;
  v_expires timestamptz;
begin
  if v_uid is null then raise exception using message='not_authenticated'; end if;
  perform public.nostra_cleanup_expired_holds_v161();

  select hold_minutes, max_hold_vehicles into v_hold_minutes, v_max
  from public.nostra_logistics_settings_v161 where singleton = true;
  v_hold_minutes := coalesce(v_hold_minutes,20);
  v_max := coalesce(v_max,10);
  v_expires := now() + make_interval(mins => v_hold_minutes);

  select coalesce(sum(greatest(ci.quantity,1)),0)::integer into v_total
  from public.cart_items ci
  join public.catalog_vehicles cv on cv.id=ci.vehicle_id
  where ci.user_id=v_uid and ci.item_type='vehicle' and ci.vehicle_id is not null
    and coalesce(cv.catalog_type,'standard')<>'concession';

  if v_total > v_max then raise exception using message='hold_limit_reached'; end if;

  -- Verrouille les fiches dans un ordre stable pour éviter les doubles réservations.
  perform 1
  from public.catalog_vehicles cv
  where cv.id in (
    select distinct ci.vehicle_id from public.cart_items ci
    join public.catalog_vehicles ccv on ccv.id=ci.vehicle_id
    where ci.user_id=v_uid and ci.item_type='vehicle' and ci.vehicle_id is not null
      and coalesce(ccv.catalog_type,'standard')<>'concession'
  )
  order by cv.id
  for update;

  for v_line in
    select ci.vehicle_id, sum(greatest(ci.quantity,1))::integer as quantity
    from public.cart_items ci
    join public.catalog_vehicles cv on cv.id=ci.vehicle_id
    where ci.user_id=v_uid and ci.item_type='vehicle' and ci.vehicle_id is not null
      and coalesce(cv.catalog_type,'standard')<>'concession'
    group by ci.vehicle_id
    order by ci.vehicle_id
  loop
    select coalesce(sum(quantity),0)::integer into v_other
    from public.nostra_vehicle_holds_v161
    where vehicle_id=v_line.vehicle_id
      and user_id<>v_uid
      and status='active' and expires_at>now();

    if (select greatest(coalesce(stock_quantity,0),0) from public.catalog_vehicles where id=v_line.vehicle_id)
       < v_other + v_line.quantity then
      raise exception using message='vehicle_temporarily_reserved';
    end if;

    select id into v_existing_id
    from public.nostra_vehicle_holds_v161
    where user_id=v_uid and vehicle_id=v_line.vehicle_id and status='active'
    order by id desc limit 1 for update;

    if v_existing_id is null then
      insert into public.nostra_vehicle_holds_v161(user_id,vehicle_id,quantity,status,expires_at)
      values(v_uid,v_line.vehicle_id,v_line.quantity,'active',v_expires);
    else
      update public.nostra_vehicle_holds_v161
      set quantity=v_line.quantity, expires_at=v_expires, updated_at=now()
      where id=v_existing_id;
    end if;
  end loop;

  -- Libère les holds qui ne correspondent plus à aucune ligne panier.
  update public.nostra_vehicle_holds_v161 h
  set status='released', updated_at=now()
  where h.user_id=v_uid and h.status='active'
    and not exists (
      select 1 from public.cart_items ci
      where ci.user_id=v_uid and ci.item_type='vehicle' and ci.vehicle_id=h.vehicle_id
    );

  return jsonb_build_object('expires_at',v_expires,'vehicle_count',v_total,'hold_minutes',v_hold_minutes);
end;
$$;

revoke all on function public.nostra_refresh_my_cart_holds_v161() from public, anon;
grant execute on function public.nostra_refresh_my_cart_holds_v161() to authenticated;

create or replace function public.nostra_add_vehicle_selection_to_cart_v161(
  p_vehicle_ids bigint[],
  p_delivery_mode text,
  p_delivery_address text default null,
  p_delivery_phone text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_unique bigint[];
  v_to_add bigint[];
  v_id bigint;
  v_other integer;
  v_stock integer;
  v_result jsonb := '{}'::jsonb;
  v_hold jsonb;
begin
  if v_uid is null then raise exception using message='not_authenticated'; end if;
  perform public.nostra_cleanup_expired_holds_v161();

  select array_agg(id order by id) into v_unique
  from (
    select distinct value as id
    from unnest(coalesce(p_vehicle_ids,array[]::bigint[])) u(value)
    where value is not null and value>0
    limit 50
  ) s;
  if coalesce(array_length(v_unique,1),0)=0 then raise exception using message='selection_empty'; end if;

  select array_agg(id order by id) into v_to_add
  from unnest(v_unique) u(id)
  where not exists (
    select 1 from public.cart_items ci
    where ci.user_id=v_uid and ci.item_type='vehicle' and ci.vehicle_id=u.id
  );

  if coalesce(array_length(v_to_add,1),0)>0 then
    perform 1 from public.catalog_vehicles where id=any(v_to_add) order by id for update;
    foreach v_id in array v_to_add loop
      select greatest(coalesce(stock_quantity,0),0) into v_stock
      from public.catalog_vehicles where id=v_id and published=true;
      if v_stock is null then raise exception using message='vehicle_unavailable'; end if;
      select coalesce(sum(quantity),0)::integer into v_other
      from public.nostra_vehicle_holds_v161
      where vehicle_id=v_id and user_id<>v_uid and status='active' and expires_at>now();
      if v_stock <= v_other then raise exception using message='vehicle_temporarily_reserved'; end if;
    end loop;

    v_result := public.nostra_add_vehicle_selection_to_cart_v1601(
      v_to_add,p_delivery_mode,p_delivery_address,p_delivery_phone
    );
  else
    v_result := public.nostra_prepare_cart_delivery_v160(
      p_delivery_mode,
      case when p_delivery_mode='home' then p_delivery_address else null end,
      case when p_delivery_mode='home' then p_delivery_phone else null end
    );
  end if;

  v_hold := public.nostra_refresh_my_cart_holds_v161();
  return jsonb_build_object(
    'added_count',coalesce(array_length(v_to_add,1),0),
    'selected_count',coalesce(array_length(v_unique,1),0),
    'hold',v_hold,
    'result',coalesce(v_result,'{}'::jsonb)
  );
end;
$$;

revoke all on function public.nostra_add_vehicle_selection_to_cart_v161(bigint[],text,text,text) from public, anon;
grant execute on function public.nostra_add_vehicle_selection_to_cart_v161(bigint[],text,text,text) to authenticated;

create or replace function public.nostra_add_vehicle_purchase_to_cart_v161(
  p_vehicle_id bigint,
  p_delivery_mode text,
  p_delivery_address text default null,
  p_delivery_phone text default null,
  p_purchase_mode text default 'order'
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_stock integer;
  v_other integer;
  v_cart_qty integer;
  v_result jsonb;
  v_hold jsonb;
  v_catalog_type text;
begin
  if v_uid is null then raise exception using message='not_authenticated'; end if;
  perform public.nostra_cleanup_expired_holds_v161();

  -- Les réservations avec acompte conservent leur moteur V93, mais respectent
  -- quand même les blocages temporaires déjà posés par d'autres citoyens.
  if coalesce(p_purchase_mode,'order') <> 'order' then
    select greatest(coalesce(stock_quantity,0),0), coalesce(catalog_type,'standard')
    into v_stock, v_catalog_type
    from public.catalog_vehicles where id=p_vehicle_id and published=true
    for update;
    if v_stock is null then raise exception using message='vehicle_unavailable'; end if;
    if v_catalog_type<>'concession' then
      select coalesce(sum(quantity),0)::integer into v_other
      from public.nostra_vehicle_holds_v161
      where vehicle_id=p_vehicle_id and user_id<>v_uid and status='active' and expires_at>now();
      if v_stock <= v_other then raise exception using message='vehicle_temporarily_reserved'; end if;
    end if;
    return public.add_vehicle_purchase_to_cart_v93(p_vehicle_id,p_delivery_mode,p_delivery_address,p_delivery_phone,p_purchase_mode);
  end if;

  select greatest(coalesce(stock_quantity,0),0), coalesce(catalog_type,'standard')
  into v_stock, v_catalog_type
  from public.catalog_vehicles where id=p_vehicle_id and published=true
  for update;
  if v_stock is null then raise exception using message='vehicle_unavailable'; end if;

  -- Location : pas de réservation temporaire V161.
  if v_catalog_type='concession' then
    return public.add_vehicle_purchase_to_cart_v93(p_vehicle_id,p_delivery_mode,p_delivery_address,p_delivery_phone,p_purchase_mode);
  end if;

  select coalesce(sum(quantity),0)::integer into v_other
  from public.nostra_vehicle_holds_v161
  where vehicle_id=p_vehicle_id and user_id<>v_uid and status='active' and expires_at>now();
  select coalesce(sum(greatest(quantity,1)),0)::integer into v_cart_qty
  from public.cart_items
  where user_id=v_uid and item_type='vehicle' and vehicle_id=p_vehicle_id;

  if v_stock < v_other + v_cart_qty + 1 then
    raise exception using message='vehicle_temporarily_reserved';
  end if;

  v_result := public.add_vehicle_purchase_to_cart_v93(p_vehicle_id,p_delivery_mode,p_delivery_address,p_delivery_phone,p_purchase_mode);
  v_hold := public.nostra_refresh_my_cart_holds_v161();
  return coalesce(v_result,'{}'::jsonb) || jsonb_build_object('hold',v_hold);
end;
$$;

revoke all on function public.nostra_add_vehicle_purchase_to_cart_v161(bigint,text,text,text,text) from public, anon;
grant execute on function public.nostra_add_vehicle_purchase_to_cart_v161(bigint,text,text,text,text) to authenticated;

