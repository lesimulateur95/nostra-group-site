create or replace function public.update_vehicle_reservation_followup_v96(
  p_reservation_id bigint,
  p_status text default null,
  p_assigned_staff text default null,
  p_payment_due_at timestamptz default null,
  p_admin_note text default null,
  p_internal_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_reservation public.vehicle_reservations%rowtype;
  v_order_status text;
begin
  if not public.nostra_can_manage_vehicle_reservations_v93() then
    raise exception using message = 'forbidden';
  end if;

  select * into v_reservation
  from public.vehicle_reservations
  where id = p_reservation_id
  for update;

  if not found then
    raise exception using message = 'reservation_not_found';
  end if;

  if p_status is not null then
    if p_status not in ('paid_full', 'preparing', 'ready', 'completed') then
      raise exception using message = 'invalid_reservation_status';
    end if;
    if v_reservation.status not in ('paid_full', 'preparing', 'ready', 'completed') then
      raise exception using message = 'reservation_status_locked';
    end if;

    v_order_status := case p_status
      when 'paid_full' then 'confirmed'
      when 'preparing' then 'preparing'
      when 'ready' then 'ready'
      when 'completed' then 'completed'
      else 'confirmed'
    end;

    if v_reservation.final_order_id is not null then
      update public.orders
      set status = v_order_status,
          admin_note = nullif(btrim(coalesce(p_admin_note, '')), ''),
          updated_at = now()
      where id = v_reservation.final_order_id;
    else
      update public.vehicle_reservations
      set status = p_status
      where id = p_reservation_id;
    end if;
  end if;

  update public.vehicle_reservations
  set assigned_staff = nullif(btrim(coalesce(p_assigned_staff, '')), ''),
      payment_due_at = p_payment_due_at,
      admin_note = nullif(btrim(coalesce(p_admin_note, '')), ''),
      updated_at = now()
  where id = p_reservation_id;

  insert into public.vehicle_reservation_private_v96 (
    reservation_id, internal_note, updated_at
  ) values (
    p_reservation_id,
    nullif(btrim(coalesce(p_internal_note, '')), ''),
    now()
  )
  on conflict (reservation_id) do update
  set internal_note = excluded.internal_note,
      updated_at = now();

  return jsonb_build_object(
    'id', p_reservation_id,
    'status', coalesce(p_status, v_reservation.status)
  );
end;
$$;

-- Le statut de la commande finale alimente automatiquement la frise client.
create or replace function public.nostra_sync_reservation_order_status_v93()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'DELETE' then
    update public.vehicle_reservations
    set status = 'cancelled',
        stock_reserved = false,
        final_order_id = null,
        updated_at = now()
    where final_order_id = old.id;
    return old;
  end if;

  update public.vehicle_reservations
  set status = case
        when new.status = 'completed' then 'completed'
        when new.status = 'ready' then 'ready'
        when new.status = 'preparing' then 'preparing'
        when new.status = 'cancelled' then 'cancelled'
        else 'paid_full'
      end,
      stock_reserved = case when new.status = 'cancelled' then false else stock_reserved end,
      preparation_started_at = case
        when new.status in ('preparing', 'ready', 'completed')
          then coalesce(preparation_started_at, now())
        else preparation_started_at
      end,
      ready_at = case
        when new.status in ('ready', 'completed') then coalesce(ready_at, now())
        else ready_at
      end,
      delivered_at = case
        when new.status = 'completed' then coalesce(delivered_at, now())
        else delivered_at
      end,
      updated_at = now()
  where final_order_id = new.id;
  return new;
end;
$$;

