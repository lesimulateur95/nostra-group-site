create or replace function public.submit_recruitment_application_v96(
  p_candidate_name text,
  p_discord_name text,
  p_phone text,
  p_position text,
  p_availability text,
  p_motivation text,
  p_experience text default null,
  p_strengths text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_application_id bigint;
  v_application_number text;
begin
  if v_user_id is null then
    raise exception using message = 'not_authenticated';
  end if;

  if length(btrim(coalesce(p_candidate_name, ''))) < 2
     or length(btrim(coalesce(p_position, ''))) < 2
     or length(btrim(coalesce(p_availability, ''))) < 3
     or length(btrim(coalesce(p_motivation, ''))) < 20 then
    raise exception using message = 'invalid_application';
  end if;

  if exists (
    select 1
    from public.recruitment_applications
    where user_id = v_user_id
      and status in ('new', 'reviewing', 'interview')
  ) then
    raise exception using message = 'application_already_active';
  end if;

  v_application_number := 'REC-' || to_char(clock_timestamp(), 'YYYYMMDD') || '-' ||
    upper(substr(md5(random()::text || clock_timestamp()::text || v_user_id::text), 1, 7));

  insert into public.recruitment_applications (
    application_number,
    user_id,
    candidate_name,
    discord_name,
    phone,
    position,
    availability,
    motivation,
    experience,
    strengths,
    status,
    created_at,
    updated_at
  ) values (
    v_application_number,
    v_user_id,
    btrim(p_candidate_name),
    nullif(btrim(coalesce(p_discord_name, '')), ''),
    nullif(btrim(coalesce(p_phone, '')), ''),
    btrim(p_position),
    btrim(p_availability),
    btrim(p_motivation),
    nullif(btrim(coalesce(p_experience, '')), ''),
    nullif(btrim(coalesce(p_strengths, '')), ''),
    'new',
    now(),
    now()
  ) returning id into v_application_id;

  insert into public.recruitment_application_history (
    application_id, actor_user_id, from_status, to_status, note
  ) values (
    v_application_id, v_user_id, null, 'new', 'Candidature envoyée depuis le site.'
  );

  return jsonb_build_object(
    'id', v_application_id,
    'application_number', v_application_number
  );
end;
$$;

create or replace function public.review_recruitment_application_v96(
  p_application_id bigint,
  p_status text,
  p_assigned_to text default null,
  p_interview_at timestamptz default null,
  p_internal_notes text default null,
  p_manager_response text default null,
  p_history_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_application public.recruitment_applications%rowtype;
begin
  if not public.nostra_is_manager_v96() then
    raise exception using message = 'forbidden';
  end if;
  if coalesce(p_status, '') not in ('new', 'reviewing', 'interview', 'accepted', 'refused', 'archived') then
    raise exception using message = 'invalid_application';
  end if;

  select * into v_application
  from public.recruitment_applications
  where id = p_application_id
  for update;

  if not found then
    raise exception using message = 'application_not_found';
  end if;

  if p_status = 'interview' and p_interview_at is null then
    raise exception using message = 'interview_date_required';
  end if;

  update public.recruitment_applications
  set status = p_status,
      assigned_to = nullif(btrim(coalesce(p_assigned_to, '')), ''),
      interview_at = p_interview_at,
      manager_response = nullif(btrim(coalesce(p_manager_response, '')), ''),
      updated_at = now()
  where id = p_application_id;

  insert into public.recruitment_application_private_v96 (
    application_id, internal_notes, updated_at
  ) values (
    p_application_id,
    nullif(btrim(coalesce(p_internal_notes, '')), ''),
    now()
  )
  on conflict (application_id) do update
  set internal_notes = excluded.internal_notes,
      updated_at = now();

  if v_application.status is distinct from p_status
     or nullif(btrim(coalesce(p_history_note, '')), '') is not null then
    insert into public.recruitment_application_history (
      application_id, actor_user_id, from_status, to_status, note
    ) values (
      p_application_id,
      auth.uid(),
      v_application.status,
      p_status,
      nullif(btrim(coalesce(p_history_note, '')), '')
    );
  end if;

  return jsonb_build_object('status', p_status);
end;
$$;

