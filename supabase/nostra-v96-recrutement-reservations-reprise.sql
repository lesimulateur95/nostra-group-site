create or replace function public.nostra_reservation_followup_defaults_v96()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.status = 'balance_due' and new.payment_due_at is null then
    new.payment_due_at := now() + interval '7 days';
  end if;

  if new.status = 'preparing' and new.preparation_started_at is null then
    new.preparation_started_at := now();
  end if;
  if new.status = 'ready' then
    new.preparation_started_at := coalesce(new.preparation_started_at, now());
    new.ready_at := coalesce(new.ready_at, now());
  end if;
  if new.status = 'completed' then
    new.preparation_started_at := coalesce(new.preparation_started_at, now());
    new.ready_at := coalesce(new.ready_at, now());
    new.delivered_at := coalesce(new.delivered_at, now());
  end if;

  return new;
end;
$$;

