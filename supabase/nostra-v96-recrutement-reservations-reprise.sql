create or replace function public.cancel_vehicle_trade_in_v96(
  p_request_id bigint
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_request public.vehicle_trade_in_requests%rowtype;
begin
  if auth.uid() is null then
    raise exception using message = 'not_authenticated';
  end if;

  select * into v_request
  from public.vehicle_trade_in_requests
  where id = p_request_id
    and user_id = auth.uid()
  for update;

  if not found then
    raise exception using message = 'trade_in_not_found';
  end if;
  if v_request.status not in ('new', 'reviewing', 'offer_sent') then
    raise exception using message = 'request_not_cancellable';
  end if;

  update public.vehicle_trade_in_requests
  set status = 'cancelled', updated_at = now()
  where id = p_request_id;

  return jsonb_build_object('status', 'cancelled');
end;
$$;

