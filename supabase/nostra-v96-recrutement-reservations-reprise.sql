  v_condition text := lower(btrim(coalesce(p_vehicle_condition, 'good')));
begin
  if v_user_id is null then
    raise exception using message = 'not_authenticated';
  end if;
  if length(btrim(coalesce(p_brand, ''))) < 1
     or length(btrim(coalesce(p_model, ''))) < 1
     or length(btrim(coalesce(p_description, ''))) < 10
     or coalesce(p_mileage, 0) < 0
     or v_condition not in ('excellent', 'very_good', 'good', 'fair', 'repair') then
    raise exception using message = 'invalid_trade_in';
  end if;

  v_request_number := 'REP-' || to_char(clock_timestamp(), 'YYYYMMDD') || '-' ||
    upper(substr(md5(random()::text || clock_timestamp()::text || v_user_id::text), 1, 7));

  insert into public.vehicle_trade_in_requests (
    request_number,
    user_id,
    customer_name,
    customer_email,
    customer_phone,
    brand,
    model,
    version,
    registration,
    mileage,
    first_registration_year,
    vehicle_condition,
    modifications,
    desired_price,
    description,
    images,
    status,
    created_at,
    updated_at
  ) values (
    v_request_number,
    v_user_id,
    btrim(p_customer_name),
    nullif(btrim(coalesce(p_customer_email, '')), ''),
    nullif(btrim(coalesce(p_customer_phone, '')), ''),
    btrim(p_brand),
    btrim(p_model),
    nullif(btrim(coalesce(p_version, '')), ''),
    nullif(upper(btrim(coalesce(p_registration, ''))), ''),
    greatest(coalesce(p_mileage, 0), 0),
    case
      when p_first_registration_year between 1950 and 2100 then p_first_registration_year
      else null
    end,
    v_condition,
    nullif(btrim(coalesce(p_modifications, '')), ''),
    case when coalesce(p_desired_price, 0) > 0 then p_desired_price else null end,
    btrim(p_description),
    case when jsonb_typeof(coalesce(p_images, '[]'::jsonb)) = 'array'
      then coalesce(p_images, '[]'::jsonb)
      else '[]'::jsonb
    end,
    'new',
    now(),
    now()
  ) returning id into v_request_id;

  return jsonb_build_object(
    'id', v_request_id,
    'request_number', v_request_number
  );
end;
$$;

create or replace function public.review_vehicle_trade_in_v96(
  p_request_id bigint,
  p_status text,
  p_proposed_purchase_price numeric default null,
  p_planned_resale_price numeric default null,
  p_assigned_staff text default null,
  p_appointment_at timestamptz default null,
  p_admin_note text default null,
  p_internal_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_request public.vehicle_trade_in_requests%rowtype;
begin
  if not public.nostra_can_manage_trade_ins_v96() then
    raise exception using message = 'forbidden';
  end if;
  if coalesce(p_status, '') not in ('new', 'reviewing', 'offer_sent', 'accepted', 'refused', 'cancelled') then
    raise exception using message = 'invalid_trade_in';
  end if;

  select * into v_request
  from public.vehicle_trade_in_requests
  where id = p_request_id
  for update;

  if not found then
    raise exception using message = 'trade_in_not_found';
  end if;
  if v_request.status = 'converted' then
    raise exception using message = 'request_not_convertible';
  end if;
  if p_status in ('offer_sent', 'accepted')
     and coalesce(p_proposed_purchase_price, 0) <= 0 then
    raise exception using message = 'purchase_price_required';
  end if;
  if p_status = 'accepted'
     and coalesce(p_planned_resale_price, 0) <= 0 then
    raise exception using message = 'resale_price_required';
  end if;

  update public.vehicle_trade_in_requests
  set status = p_status,
      proposed_purchase_price = case
        when coalesce(p_proposed_purchase_price, 0) > 0 then p_proposed_purchase_price
        else null
      end,
      assigned_staff = nullif(btrim(coalesce(p_assigned_staff, '')), ''),
      appointment_at = p_appointment_at,
      admin_note = nullif(btrim(coalesce(p_admin_note, '')), ''),
      updated_at = now()
  where id = p_request_id;

  insert into public.vehicle_trade_in_private_v96 (
    request_id, planned_resale_price, internal_note, updated_at
  ) values (
    p_request_id,
    case
      when coalesce(p_planned_resale_price, 0) > 0 then p_planned_resale_price
      else null
    end,
    nullif(btrim(coalesce(p_internal_note, '')), ''),
    now()
  )
  on conflict (request_id) do update
  set planned_resale_price = excluded.planned_resale_price,
      internal_note = excluded.internal_note,
      updated_at = now();

  return jsonb_build_object('status', p_status);
end;
$$;

create or replace function public.convert_vehicle_trade_in_to_used_vehicle_v96(
  p_request_id bigint
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_request public.vehicle_trade_in_requests%rowtype;
  v_private public.vehicle_trade_in_private_v96%rowtype;
  v_vehicle_id bigint;
begin
  if not public.nostra_can_manage_trade_ins_v96() then
    raise exception using message = 'forbidden';
  end if;

  select * into v_request
  from public.vehicle_trade_in_requests
  where id = p_request_id
  for update;

  if not found then
    raise exception using message = 'trade_in_not_found';
  end if;

  select * into v_private
  from public.vehicle_trade_in_private_v96
  where request_id = p_request_id;

  if v_request.status <> 'accepted'
     or coalesce(v_request.proposed_purchase_price, 0) <= 0
     or coalesce(v_private.planned_resale_price, 0) <= 0 then
    raise exception using message = 'request_not_convertible';
  end if;

  select public.create_used_vehicle_v92(
    p_brand => v_request.brand,
    p_model => v_request.model,
    p_version => v_request.version,
    p_registration => v_request.registration,
    p_previous_owner => v_request.customer_name,
    p_purchase_date => current_date,
    p_purchase_price => v_request.proposed_purchase_price,
    p_resale_price => v_private.planned_resale_price,
    p_quantity => 1,
    p_images => v_request.images,
    p_description => v_request.description,
    p_condition => v_request.vehicle_condition,
    p_internal_notes => btrim(
      'Créé depuis la demande de reprise ' || v_request.request_number || '. ' ||
      coalesce(v_private.internal_note, '')
    ),
    p_trunk_capacity => '',
    p_top_speed => '',
    p_power => '',
    p_sort_order => 0,
    p_published => false
  ) into v_vehicle_id;

  if coalesce(v_vehicle_id, 0) <= 0 then
    raise exception using message = 'vehicle_creation_failed';
  end if;

  update public.vehicle_trade_in_requests
  set status = 'converted',
      converted_vehicle_id = v_vehicle_id,
      updated_at = now()
  where id = p_request_id;

  return jsonb_build_object(
    'status', 'converted',
    'vehicle_id', v_vehicle_id,
    'request_number', v_request.request_number
  );
end;
$$;

create or replace function public.mark_vehicle_trade_in_converted_v96(
  p_request_id bigint,
  p_vehicle_id bigint
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_request public.vehicle_trade_in_requests%rowtype;
  v_private public.vehicle_trade_in_private_v96%rowtype;
begin
  if not public.nostra_can_manage_trade_ins_v96() then
    raise exception using message = 'forbidden';
  end if;

  select * into v_request
  from public.vehicle_trade_in_requests
  where id = p_request_id
  for update;

  if not found then
    raise exception using message = 'request_not_convertible';
