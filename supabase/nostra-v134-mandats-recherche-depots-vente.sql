create or replace function public.choose_vehicle_search_proposal_v134(p_proposal_id bigint)
returns void language plpgsql security definer set search_path = public as $$
declare v_mandate_id bigint;
begin
  select p.mandate_id into v_mandate_id
  from public.vehicle_search_proposals_v134 p
  join public.vehicle_search_mandates_v134 m on m.id = p.mandate_id
  where p.id = p_proposal_id and m.user_id = auth.uid() and m.status in ('searching','proposed')
  for update of p, m;
  if not found then raise exception using message = 'proposal_unavailable'; end if;
  update public.vehicle_search_proposals_v134 set status = case when id = p_proposal_id then 'selected' else 'rejected' end where mandate_id = v_mandate_id;
  update public.vehicle_search_mandates_v134 set selected_proposal_id = p_proposal_id, status = 'selected', updated_at = now() where id = v_mandate_id;
end $$;

create or replace function public.accept_vehicle_consignment_v134(p_consignment_id bigint)
returns void language plpgsql security definer set search_path = public as $$
begin
  update public.vehicle_consignments_v134
  set status = 'accepted', customer_accepted_at = now(), updated_at = now()
  where id = p_consignment_id and user_id = auth.uid() and status = 'offer_sent'
    and coalesce(agreed_sale_price,0) > 0 and coalesce(commission_amount,0) >= 0;
  if not found then raise exception using message = 'consignment_unavailable'; end if;
end $$;

create or replace function public.publish_vehicle_consignment_v134(p_consignment_id bigint)
returns bigint language plpgsql security definer set search_path = public as $$
declare c public.vehicle_consignments_v134%rowtype; v_vehicle_id bigint;
begin
  if not public.nostra_can_manage_used_vehicles_v92() then raise exception using message = 'forbidden'; end if;
  select * into c from public.vehicle_consignments_v134 where id = p_consignment_id for update;
  if not found or c.status <> 'accepted' then raise exception using message = 'consignment_not_accepted'; end if;
  if c.catalog_vehicle_id is not null then return c.catalog_vehicle_id; end if;
  insert into public.catalog_vehicles (
    brand,model,price,description,images,published,stock_quantity,sort_order,catalog_type,used_vehicle_status,used_condition,updated_at
  ) values (
    c.brand,c.model,c.agreed_sale_price,coalesce(c.public_description,c.description),c.images,true,1,0,'used','available',c.vehicle_condition,now()
  ) returning id into v_vehicle_id;
  insert into public.used_vehicle_details (
    vehicle_id,version,registration,previous_owner,purchase_date,purchase_price,resale_price,purchase_quantity,vehicle_condition,internal_notes,sale_status,created_by,updated_by
  ) values (
    v_vehicle_id,c.version,nullif(upper(btrim(coalesce(c.registration,''))),''),c.owner_name,current_date,0,c.agreed_sale_price,1,c.vehicle_condition,
    'Dépôt-vente ' || c.consignment_number || ' — Le véhicule reste la propriété du déposant jusqu’à la vente.','available',auth.uid(),auth.uid()
  );
  update public.vehicle_consignments_v134 set catalog_vehicle_id=v_vehicle_id,status='published',updated_at=now() where id=c.id;
  return v_vehicle_id;
end $$;

create or replace function public.sync_vehicle_consignment_sale_v134()
returns trigger language plpgsql security definer set search_path = public as $$
declare c public.vehicle_consignments_v134%rowtype; owner_entry bigint;
begin
  select * into c from public.vehicle_consignments_v134 where catalog_vehicle_id = new.vehicle_id for update;
  if not found then return new; end if;
  update public.used_vehicle_sales set unit_purchase_price = greatest(0,new.unit_sale_price-c.commission_amount),
    total_purchase_price = greatest(0,new.total_sale_price-c.commission_amount), margin=c.commission_amount, updated_at=now()
  where id=new.id and margin is distinct from c.commission_amount;
  insert into public.accounting_entries(entry_date,entry_type,category,label,amount,notes,nostra_source_type,nostra_source_id)
  values (new.sold_at::date,'expense','Dépôt-vente — Règlement propriétaire','Règlement ' || c.consignment_number,c.owner_net_amount,
    new.order_number || ' · ' || c.owner_name,'consignment_owner_payment',c.id::text)
  on conflict (nostra_source_type,nostra_source_id) do update set amount=excluded.amount,notes=excluded.notes
  returning id into owner_entry;
  update public.vehicle_consignments_v134 set status='sold',sold_order_id=new.order_id,sold_at=new.sold_at,
    owner_accounting_entry_id=owner_entry,updated_at=now() where id=c.id;
  return new;
end $$;

drop trigger if exists sync_vehicle_consignment_sale_v134 on public.used_vehicle_sales;
create trigger sync_vehicle_consignment_sale_v134 after insert on public.used_vehicle_sales
for each row execute function public.sync_vehicle_consignment_sale_v134();

