-- NOSTRA GROUP — V134
-- Mandats de recherche et dépôts-vente. Script réexécutable, sans suppression.

begin;

create sequence if not exists public.vehicle_search_mandate_v134_seq;
create sequence if not exists public.vehicle_consignment_v134_seq;

create table if not exists public.vehicle_search_mandates_v134 (
  id bigint generated by default as identity primary key,
  mandate_number text not null unique default (
    'MR-' || to_char(current_date, 'YYYY') || '-' || lpad(nextval('public.vehicle_search_mandate_v134_seq')::text, 5, '0')
  ),
  user_id uuid not null references auth.users(id) on delete cascade,
  customer_name text not null,
  customer_email text,
  customer_phone text,
  brand text,
  model text,
  vehicle_type text,
  budget_min numeric(14,2) not null default 0 check (budget_min >= 0),
  budget_max numeric(14,2) not null check (budget_max > 0),
  year_min integer,
  max_mileage integer check (max_mileage is null or max_mileage >= 0),
  required_features text,
  notes text,
  status text not null default 'new'
    check (status in ('new','searching','proposed','selected','closed','refused','cancelled')),
  assigned_staff text,
  staff_note text,
  selected_proposal_id bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.vehicle_search_proposals_v134 (
  id bigint generated by default as identity primary key,
  mandate_id bigint not null references public.vehicle_search_mandates_v134(id) on delete cascade,
  vehicle_name text not null,
  price numeric(14,2) not null check (price > 0),
  year integer,
  mileage integer check (mileage is null or mileage >= 0),
  source_url text,
  details text,
  status text not null default 'proposed'
    check (status in ('proposed','selected','rejected','withdrawn')),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

do $$ begin
  alter table public.vehicle_search_mandates_v134
    add constraint vehicle_search_selected_proposal_v134_fk
    foreign key (selected_proposal_id)
    references public.vehicle_search_proposals_v134(id) on delete set null;
exception when duplicate_object then null; end $$;

create table if not exists public.vehicle_consignments_v134 (
  id bigint generated by default as identity primary key,
  consignment_number text not null unique default (
    'DV-' || to_char(current_date, 'YYYY') || '-' || lpad(nextval('public.vehicle_consignment_v134_seq')::text, 5, '0')
  ),
  user_id uuid not null references auth.users(id) on delete cascade,
  owner_name text not null,
  owner_email text,
  owner_phone text,
  brand text not null,
  model text not null,
  version text,
  registration text,
  mileage integer not null default 0 check (mileage >= 0),
  first_registration_year integer,
  vehicle_condition text not null default 'good'
    check (vehicle_condition in ('excellent','very_good','good','fair','repair')),
  description text not null,
  images jsonb not null default '[]'::jsonb,
  desired_price numeric(14,2) not null check (desired_price > 0),
  agreed_sale_price numeric(14,2),
  commission_rate numeric(6,2) check (commission_rate is null or commission_rate between 0 and 100),
  commission_amount numeric(14,2),
  owner_net_amount numeric(14,2),
  status text not null default 'new'
    check (status in ('new','reviewing','offer_sent','accepted','published','reserved','sold','refused','cancelled')),
  assigned_staff text,
  public_description text,
  staff_note text,
  customer_accepted_at timestamptz,
  catalog_vehicle_id bigint references public.catalog_vehicles(id) on delete set null,
  sold_order_id bigint references public.orders(id) on delete set null,
  sold_at timestamptz,
  owner_paid_at timestamptz,
  owner_accounting_entry_id bigint references public.accounting_entries(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists vehicle_search_mandates_v134_user_idx
  on public.vehicle_search_mandates_v134(user_id, created_at desc);
create index if not exists vehicle_search_proposals_v134_mandate_idx
  on public.vehicle_search_proposals_v134(mandate_id, created_at desc);
create index if not exists vehicle_consignments_v134_user_idx
  on public.vehicle_consignments_v134(user_id, created_at desc);
create unique index if not exists vehicle_consignments_v134_catalog_uq
  on public.vehicle_consignments_v134(catalog_vehicle_id) where catalog_vehicle_id is not null;

alter table public.vehicle_search_mandates_v134 enable row level security;
