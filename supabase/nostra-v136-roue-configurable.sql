create table if not exists public.game_wheel_settings (
  id integer primary key default 1 check (id = 1),
  enabled boolean not null default true,
  disabled_message text not null default 'La roue de la chance est temporairement indisponible. Reviens prochainement pour tenter ta chance.',
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now(),
  constraint game_wheel_settings_message_length check (char_length(disabled_message) between 1 and 500)
);

create table if not exists public.game_wheel_segments (
  id bigint generated by default as identity primary key,
  slot_index integer not null unique check (slot_index between 0 and 39),
  prize_key text not null,
  label text not null check (char_length(label) between 1 and 100),
  short_label text not null check (char_length(short_label) between 1 and 18),
  prize_type text not null check (prize_type in ('bonus', 'loss')),
  color text not null check (color ~ '^#[0-9A-Fa-f]{6}$'),
  text_color text not null check (text_color ~ '^#[0-9A-Fa-f]{6}$'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

