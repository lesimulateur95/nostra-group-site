create or replace function public.save_nostra_wheel_configuration(
  p_enabled boolean,
  p_disabled_message text,
  p_segments jsonb
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_count integer;
begin
  if auth.uid() is null or not public.nostra_games_is_manager() then
    raise exception using errcode = '42501', message = 'manager_access_required';
  end if;

  if p_disabled_message is null or char_length(trim(p_disabled_message)) not between 1 and 500 then
    raise exception using errcode = '22023', message = 'invalid_disabled_message';
  end if;

  if p_segments is null or jsonb_typeof(p_segments) <> 'array' then
    raise exception using errcode = '22023', message = 'invalid_wheel_segments';
  end if;

  v_count := jsonb_array_length(p_segments);
  if v_count not between 2 and 40 then
    raise exception using errcode = '22023', message = 'wheel_segment_count_must_be_between_2_and_40';
  end if;

  if exists (
    select 1
    from jsonb_array_elements(p_segments) with ordinality as item(value, position)
    where coalesce(char_length(trim(value->>'label')), 0) not between 1 and 100
       or coalesce(char_length(trim(value->>'short_label')), 0) not between 1 and 18
       or coalesce(value->>'prize_type', '') not in ('bonus', 'loss')
       or coalesce(value->>'color', '') !~ '^#[0-9A-Fa-f]{6}$'
       or coalesce(value->>'text_color', '') !~ '^#[0-9A-Fa-f]{6}$'
  ) then
    raise exception using errcode = '22023', message = 'invalid_wheel_segment';
  end if;

  update public.game_wheel_settings
  set enabled = coalesce(p_enabled, false),
      disabled_message = trim(p_disabled_message),
      updated_by = auth.uid(),
      updated_at = now()
  where id = 1;

  delete from public.game_wheel_segments;

  insert into public.game_wheel_segments (
    slot_index,
    prize_key,
    label,
    short_label,
    prize_type,
    color,
    text_color,
    created_at,
    updated_at
  )
  select
    position::integer - 1,
    coalesce(nullif(trim(value->>'prize_key'), ''), 'custom_' || (position::integer - 1)::text),
    trim(value->>'label'),
    trim(value->>'short_label'),
    value->>'prize_type',
    value->>'color',
    value->>'text_color',
    now(),
    now()
  from jsonb_array_elements(p_segments) with ordinality as item(value, position)
  order by position;
end;
$$;

revoke all on function public.save_nostra_wheel_configuration(boolean, text, jsonb) from public;
grant execute on function public.save_nostra_wheel_configuration(boolean, text, jsonb) to authenticated;

create or replace function public.spin_nostra_wheel()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_player_name text;
  v_slot integer;
  v_prize_key text;
  v_prize_label text;
  v_prize_type text;
  v_status text;
  v_spin_id bigint;
  v_draw_date date := (clock_timestamp() at time zone 'Europe/Paris')::date;
  v_enabled boolean;
begin
  if v_user_id is null then
    raise exception using errcode = '42501', message = 'not_authenticated';
  end if;

  select enabled into v_enabled from public.game_wheel_settings where id = 1;
  if coalesce(v_enabled, false) is not true then
    raise exception using errcode = 'P0001', message = 'wheel_disabled';
  end if;

  if exists (
    select 1 from public.game_wheel_spins
    where user_id = v_user_id and draw_date = v_draw_date
  ) then
    raise exception using errcode = 'P0001', message = 'daily_spin_limit';
  end if;

  select nullif(trim(concat_ws(' ', rp_first_name, rp_last_name)), '')
    into v_player_name
  from public.member_profiles
  where user_id = v_user_id;

  if v_player_name is null then
    select nullif(trim(coalesce(discord_name, '')), '')
      into v_player_name
    from public.member_profiles
    where user_id = v_user_id;
  end if;

  v_player_name := coalesce(v_player_name, 'Citoyen Nostra Group');

  select slot_index, prize_key, label, prize_type
    into v_slot, v_prize_key, v_prize_label, v_prize_type
  from public.game_wheel_segments
  order by random()
  limit 1;

  if v_slot is null then
    raise exception using errcode = 'P0001', message = 'wheel_has_no_segments';
  end if;

  v_status := case when v_prize_type = 'loss' then 'lost' else 'unused' end;

  begin
    insert into public.game_wheel_spins (
      user_id, player_name, slot_index, prize_key, prize_label,
      prize_type, redemption_status, draw_date
    ) values (
      v_user_id, v_player_name, v_slot, v_prize_key, v_prize_label,
      v_prize_type, v_status, v_draw_date
    ) returning id into v_spin_id;
  exception when unique_violation then
    raise exception using errcode = 'P0001', message = 'daily_spin_limit';
  end;

  return jsonb_build_object(
    'id', v_spin_id,
    'slot_index', v_slot,
    'prize_key', v_prize_key,
    'prize_label', v_prize_label,
    'prize_type', v_prize_type,
    'redemption_status', v_status
  );
end;
$$;

revoke all on function public.spin_nostra_wheel() from public;
grant execute on function public.spin_nostra_wheel() to authenticated;

notify pgrst, 'reload schema';
