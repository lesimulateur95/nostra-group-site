-- NOSTRA GROUP V88 — CENTRE DE REMISE À ZÉRO DES DONNÉES DE TEST
--
-- Objectifs :
--   • supprimer individuellement une ancienne partie de la Roue de la Fortune ;
--   • remettre à zéro chaque jeu séparément ou tous les jeux d'un seul coup ;
--   • vider les documents de test et remettre leurs compteurs au départ ;
--   • remettre uniquement le compteur des factures à zéro quand il n'existe plus de facture.
--
-- IMPORTANT : aucune action destructive n'est exécutée pendant l'installation.
-- Les suppressions ne se produisent qu'après une action volontaire depuis le Dashboard,
-- avec rôle Gérant et phrase de confirmation exacte.

begin;

create or replace function public.nostra_v88_is_manager()
returns boolean
language plpgsql
stable
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_allowed boolean := false;
begin
  if auth.uid() is null then
    return false;
  end if;

  begin
    if to_regprocedure('public.nostra_has_role(text)') is not null then
      execute 'select coalesce(public.nostra_has_role($1), false)'
        into v_allowed
        using 'manager';
      if v_allowed then
        return true;
      end if;
    end if;
  exception when others then
    v_allowed := false;
  end;

  begin
    if to_regprocedure('public.has_nostra_dashboard_access()') is not null then
      execute 'select coalesce(public.has_nostra_dashboard_access(), false)'
        into v_allowed;
      if v_allowed then
        return true;
      end if;
    end if;
  exception when others then
    v_allowed := false;
  end;

  if to_regclass('public.member_profiles') is not null then
    begin
      execute $query$
        select exists (
          select 1
          from public.member_profiles profile
          where profile.user_id = auth.uid()
            and (
              lower(coalesce(to_jsonb(profile) ->> 'role', ''))
                in ('manager', 'gerant', 'gérant', 'direction')
              or lower(coalesce(to_jsonb(profile) ->> 'roles', ''))
                like '%manager%'
              or lower(coalesce(to_jsonb(profile) ->> 'roles', ''))
                like '%gerant%'
              or lower(coalesce(to_jsonb(profile) ->> 'roles', ''))
                like '%gérant%'
              or lower(coalesce(to_jsonb(profile) ->> 'roles', ''))
                like '%direction%'
            )
        )
      $query$ into v_allowed;
    exception when others then
      v_allowed := false;
    end;
  end if;

  return coalesce(v_allowed, false);
end;
$$;

revoke all on function public.nostra_v88_is_manager() from public;
grant execute on function public.nostra_v88_is_manager() to authenticated;

