alter table public.cart_items add column if not exists financing_installment_id bigint;

do $$
declare constraint_row record;
begin
  for constraint_row in
    select conname
    from pg_constraint
    where conrelid = 'public.cart_items'::regclass
      and contype = 'c'
      and pg_get_constraintdef(oid) ilike '%item_type%'
  loop
    execute format('alter table public.cart_items drop constraint if exists %I', constraint_row.conname);
  end loop;
end;
$$;

alter table public.cart_items
  add constraint cart_items_item_type_v125_check
  check (item_type in (
    'vehicle', 'delivery', 'reservation_deposit', 'reservation_balance',
    'financing_deposit', 'financing_installment'
  )) not valid;
alter table public.cart_items validate constraint cart_items_item_type_v125_check;

do $$
begin
  if exists (
    select 1 from pg_constraint
    where conname = 'cart_items_financing_application_id_fkey'
      and conrelid = 'public.cart_items'::regclass
  ) then
    alter table public.cart_items drop constraint cart_items_financing_application_id_fkey;
  end if;
  alter table public.cart_items
    add constraint cart_items_financing_application_id_fkey
    foreign key (financing_application_id)
    references public.vehicle_financing_applications(id)
    on delete cascade;

  if exists (
    select 1 from pg_constraint
    where conname = 'cart_items_financing_installment_id_fkey'
      and conrelid = 'public.cart_items'::regclass
  ) then
    alter table public.cart_items drop constraint cart_items_financing_installment_id_fkey;
  end if;
  alter table public.cart_items
    add constraint cart_items_financing_installment_id_fkey
    foreign key (financing_installment_id)
    references public.vehicle_financing_installments(id)
    on delete cascade;
end;
$$;

create index if not exists cart_items_financing_v125_idx
  on public.cart_items (user_id, financing_application_id, item_type);

