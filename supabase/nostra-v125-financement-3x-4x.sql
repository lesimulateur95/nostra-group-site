-- 5. Sécurité : un citoyen ne voit que ses dossiers, le Gérant voit tout
-- ---------------------------------------------------------------------------

alter table public.vehicle_financing_settings enable row level security;
alter table public.vehicle_financing_applications enable row level security;
alter table public.vehicle_financing_installments enable row level security;

drop policy if exists "financing settings readable v125" on public.vehicle_financing_settings;
create policy "financing settings readable v125"
  on public.vehicle_financing_settings for select to authenticated using (true);

drop policy if exists "financing owner reads v125" on public.vehicle_financing_applications;
create policy "financing owner reads v125"
  on public.vehicle_financing_applications for select to authenticated
  using (user_id = auth.uid());
drop policy if exists "financing manager manages v125" on public.vehicle_financing_applications;
create policy "financing manager manages v125"
  on public.vehicle_financing_applications for all to authenticated
  using (public.nostra_is_manager_v125())
  with check (public.nostra_is_manager_v125());

drop policy if exists "financing installment owner reads v125" on public.vehicle_financing_installments;
create policy "financing installment owner reads v125"
  on public.vehicle_financing_installments for select to authenticated
  using (exists (
    select 1 from public.vehicle_financing_applications application
    where application.id = application_id and application.user_id = auth.uid()
  ));
drop policy if exists "financing installment manager manages v125" on public.vehicle_financing_installments;
create policy "financing installment manager manages v125"
  on public.vehicle_financing_installments for all to authenticated
  using (public.nostra_is_manager_v125())
  with check (public.nostra_is_manager_v125());

revoke all on public.vehicle_financing_settings from public, anon;
revoke all on public.vehicle_financing_applications from public, anon;
revoke all on public.vehicle_financing_installments from public, anon;
grant select on public.vehicle_financing_settings to authenticated;
grant select on public.vehicle_financing_applications to authenticated;
grant select on public.vehicle_financing_installments to authenticated;

-- ---------------------------------------------------------------------------
-- 6. Réglages du Gérant
-- ---------------------------------------------------------------------------

create or replace function public.update_vehicle_financing_settings_v125(
  p_enabled boolean,
  p_three_times_enabled boolean,
  p_four_times_enabled boolean,
  p_three_times_fee_percent numeric,
  p_four_times_fee_percent numeric,
  p_installment_interval_days integer
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.nostra_is_manager_v125() then
    raise exception using message = 'manager_required';
  end if;
  if p_three_times_fee_percent not between 0 and 50
     or p_four_times_fee_percent not between 0 and 50
     or p_installment_interval_days not between 1 and 365 then
    raise exception using message = 'invalid_financing_settings';
  end if;

  update public.vehicle_financing_settings
  set enabled = coalesce(p_enabled, false),
      three_times_enabled = coalesce(p_three_times_enabled, false),
      four_times_enabled = coalesce(p_four_times_enabled, false),
      three_times_fee_percent = p_three_times_fee_percent,
      four_times_fee_percent = p_four_times_fee_percent,
      installment_interval_days = p_installment_interval_days,
      updated_by = auth.uid(),
      updated_at = now()
  where id = true;

  return jsonb_build_object('status', 'saved');
end;
$$;

