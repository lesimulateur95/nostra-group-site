-- NOSTRA GROUP — V125
-- Financement 3x / 4x pour les véhicules strictement supérieurs à 500 000 €.
-- Apport obligatoire de 30 %, frais automatiques et décision réservée au Gérant.
-- Script réexécutable : il ne supprime aucun dossier, paiement ou commande existant.

begin;

-- ---------------------------------------------------------------------------
-- 1. Accès Gérant
-- ---------------------------------------------------------------------------

create or replace function public.nostra_is_manager_v125()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select auth.uid() is not null
    and (
      coalesce(
        auth.jwt() -> 'user_metadata' ->> 'provider_id',
        auth.jwt() -> 'user_metadata' ->> 'discord_id',
        auth.jwt() -> 'user_metadata' ->> 'sub'
      ) = '331843410962939908'
      or exists (
        select 1
        from public.member_profiles profile
        where profile.user_id = auth.uid()
          and (
            lower(coalesce(to_jsonb(profile) ->> 'role', ''))
              in ('manager', 'gerant', 'direction', 'administrator', 'admin')
            or lower(coalesce((to_jsonb(profile) -> 'roles')::text, ''))
              ~ '(manager|gerant|direction|administrator|admin)'
          )
      )
    );
$$;

-- ---------------------------------------------------------------------------
-- 2. Réglages fixes et frais configurables
-- ---------------------------------------------------------------------------

create table if not exists public.vehicle_financing_settings (
  id boolean primary key default true check (id = true),
  enabled boolean not null default true,
  three_times_enabled boolean not null default true,
  four_times_enabled boolean not null default true,
  minimum_vehicle_price numeric(14,2) not null default 500000
    check (minimum_vehicle_price = 500000),
  down_payment_percent numeric(5,2) not null default 30
    check (down_payment_percent = 30),
  three_times_fee_percent numeric(5,2) not null default 6
    check (three_times_fee_percent between 0 and 50),
  four_times_fee_percent numeric(5,2) not null default 9
    check (four_times_fee_percent between 0 and 50),
  installment_interval_days integer not null default 30
    check (installment_interval_days between 1 and 365),
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now()
);

insert into public.vehicle_financing_settings (id)
values (true)
on conflict (id) do nothing;

-- ---------------------------------------------------------------------------
-- 3. Dossiers et échéances
-- ---------------------------------------------------------------------------

create table if not exists public.vehicle_financing_applications (
  id bigint generated by default as identity primary key,
  application_number text not null unique,
  user_id uuid not null references auth.users(id) on delete cascade,
  steam_id text,
  vehicle_id bigint not null references public.catalog_vehicles(id) on delete restrict,
  customer_name text not null,
  customer_phone text,
  vehicle_name text not null,
  catalog_type text not null default 'standard',
  vehicle_price numeric(14,2) not null check (vehicle_price > 500000),
  term_count integer not null check (term_count in (3, 4)),
  down_payment_percent numeric(5,2) not null default 30 check (down_payment_percent = 30),
  down_payment_amount numeric(14,2) not null check (down_payment_amount > 0),
  financed_principal numeric(14,2) not null check (financed_principal > 0),
  fee_percent numeric(5,2) not null check (fee_percent between 0 and 50),
  fee_amount numeric(14,2) not null check (fee_amount >= 0),
  financed_total numeric(14,2) not null check (financed_total > 0),
  delivery_mode text not null default 'showroom' check (delivery_mode in ('showroom', 'home')),
  delivery_fee numeric(14,2) not null default 0 check (delivery_fee >= 0),
  delivery_address text,
  delivery_phone text,
  customer_note text,
  status text not null default 'pending_review'
    check (status in ('pending_review', 'deposit_due', 'active', 'completed', 'rejected', 'cancelled')),
  review_note text,
  reviewed_by uuid references auth.users(id) on delete set null,
  bank_balance_at_review numeric(16,2),
  bank_checked_at timestamptz,
  reviewed_at timestamptz,
  deposit_due_at timestamptz,
  deposit_paid_at timestamptz,
  completed_at timestamptz,
  stock_reserved boolean not null default false,
  final_order_id bigint references public.orders(id) on delete set null,
  final_order_number text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.vehicle_financing_installments (
  id bigint generated by default as identity primary key,
  application_id bigint not null references public.vehicle_financing_applications(id) on delete cascade,
  installment_number integer not null check (installment_number between 1 and 4),
  amount numeric(14,2) not null check (amount > 0),
  due_at timestamptz not null,
  status text not null default 'pending' check (status in ('pending', 'paid', 'cancelled')),
  paid_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (application_id, installment_number)
);

create unique index if not exists vehicle_financing_active_user_vehicle_v125_uq
  on public.vehicle_financing_applications (user_id, vehicle_id)
  where status in ('pending_review', 'deposit_due', 'active');
create index if not exists vehicle_financing_status_v125_idx
  on public.vehicle_financing_applications (status, created_at desc);
create index if not exists vehicle_financing_user_v125_idx
  on public.vehicle_financing_applications (user_id, created_at desc);
create index if not exists vehicle_financing_installments_due_v125_idx
  on public.vehicle_financing_installments (status, due_at);

