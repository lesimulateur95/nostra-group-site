create or replace function public.nostra_upsert_used_purchase_accounting_v92(
  p_detail_id bigint
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  detail_row public.used_vehicle_details%rowtype;
  vehicle_row public.catalog_vehicles%rowtype;
  accounting_id bigint;
begin
  select * into detail_row
  from public.used_vehicle_details
  where id = p_detail_id;

  if not found then
    raise exception using message = 'used_vehicle_detail_not_found';
  end if;

  select * into vehicle_row
  from public.catalog_vehicles
  where id = detail_row.vehicle_id;

  insert into public.accounting_entries (
    entry_date,
    entry_type,
    category,
    label,
    amount,
    notes,
    nostra_source_type,
    nostra_source_id
  ) values (
    detail_row.purchase_date,
    'expense',
    'Véhicules d’occasion — Rachats',
    'Rachat ' || btrim(vehicle_row.brand || ' ' || vehicle_row.model),
    detail_row.purchase_price * greatest(detail_row.purchase_quantity, 0),
    concat_ws(
      ' · ',
      nullif('Immatriculation : ' || coalesce(detail_row.registration, ''), 'Immatriculation : '),
      nullif('Ancien propriétaire : ' || coalesce(detail_row.previous_owner, ''), 'Ancien propriétaire : '),
      'Quantité : ' || detail_row.purchase_quantity::text
    ),
    'used_purchase',
    detail_row.id::text
  )
  on conflict (nostra_source_type, nostra_source_id)
  do update set
    entry_date = excluded.entry_date,
    entry_type = excluded.entry_type,
    category = excluded.category,
    label = excluded.label,
    amount = excluded.amount,
    notes = excluded.notes
  returning id into accounting_id;

  update public.used_vehicle_details
  set purchase_accounting_entry_id = accounting_id
  where id = detail_row.id;

  return accounting_id;
end;
$$;

create or replace function public.nostra_refresh_used_vehicle_status_v92(
  p_vehicle_id bigint
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  current_stock integer := 0;
  next_status text := 'available';
begin
  select greatest(stock_quantity, 0)
  into current_stock
  from public.catalog_vehicles
  where id = p_vehicle_id
    and catalog_type = 'used';

  if not found then
    return null;
  end if;

  if current_stock > 0 then
    next_status := 'available';
  elsif exists (
    select 1
    from public.orders order_row
    cross join lateral jsonb_array_elements(coalesce(order_row.items, '[]'::jsonb)) item
    where order_row.status in ('pending', 'confirmed', 'preparing', 'ready')
      and item ->> 'item_type' = 'vehicle'
      and nullif(item ->> 'vehicle_id', '')::bigint = p_vehicle_id
  ) then
    next_status := 'reserved';
  elsif exists (
    select 1
    from public.used_vehicle_sales sale
    where sale.vehicle_id = p_vehicle_id
  ) then
    next_status := 'sold';
  else
    next_status := 'sold';
  end if;

  update public.catalog_vehicles
  set used_vehicle_status = next_status,
      updated_at = now()
  where id = p_vehicle_id;

  update public.used_vehicle_details
  set sale_status = next_status,
      updated_at = now()
  where vehicle_id = p_vehicle_id;

  return next_status;
end;
$$;

