create or replace function public.create_used_vehicle_v92(
  p_brand text,
  p_model text,
  p_version text,
  p_registration text,
  p_previous_owner text,
  p_purchase_date date,
  p_purchase_price numeric,
  p_resale_price numeric,
  p_quantity integer,
  p_images jsonb,
  p_description text,
  p_condition text,
  p_internal_notes text,
  p_trunk_capacity text,
  p_top_speed text,
  p_power text,
  p_sort_order integer,
  p_published boolean
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_vehicle_id bigint;
  detail_id bigint;
  normalized_registration text := nullif(upper(btrim(coalesce(p_registration, ''))), '');
  normalized_condition text := lower(btrim(coalesce(p_condition, 'good')));
begin
  if not public.nostra_can_manage_used_vehicles_v92() then
    raise exception using message = 'forbidden';
  end if;

  if btrim(coalesce(p_brand, '')) = ''
    or btrim(coalesce(p_model, '')) = ''
    or p_purchase_date is null
    or coalesce(p_purchase_price, 0) <= 0
    or coalesce(p_resale_price, 0) <= 0
    or coalesce(p_quantity, 0) <= 0
  then
    raise exception using message = 'invalid_used_vehicle';
  end if;

  if normalized_condition not in ('excellent', 'very_good', 'good', 'fair', 'repair') then
    normalized_condition := 'good';
  end if;

  if normalized_registration is not null and exists (
    select 1 from public.used_vehicle_details
    where lower(registration) = lower(normalized_registration)
  ) then
    raise exception using message = 'registration_already_exists';
  end if;

  insert into public.catalog_vehicles (
    brand,
    model,
    trunk_capacity,
    top_speed,
    power,
    price,
    description,
    images,
    published,
    stock_quantity,
    sort_order,
    catalog_type,
    used_vehicle_status,
    used_condition,
    updated_at
  ) values (
    btrim(p_brand),
    btrim(p_model),
    coalesce(btrim(p_trunk_capacity), ''),
    coalesce(btrim(p_top_speed), ''),
    coalesce(btrim(p_power), ''),
    p_resale_price,
    coalesce(p_description, ''),
    coalesce(p_images, '[]'::jsonb),
    coalesce(p_published, true),
    p_quantity,
    greatest(coalesce(p_sort_order, 0), 0),
    'used',
    'available',
    normalized_condition,
    now()
  )
  returning id into v_vehicle_id;

  insert into public.used_vehicle_details (
    vehicle_id,
    version,
    registration,
    previous_owner,
    purchase_date,
    purchase_price,
    resale_price,
    purchase_quantity,
    vehicle_condition,
    internal_notes,
    sale_status,
    created_by,
    updated_by
  ) values (
    v_vehicle_id,
    nullif(btrim(coalesce(p_version, '')), ''),
    normalized_registration,
    nullif(btrim(coalesce(p_previous_owner, '')), ''),
    p_purchase_date,
    p_purchase_price,
    p_resale_price,
    p_quantity,
    normalized_condition,
    nullif(btrim(coalesce(p_internal_notes, '')), ''),
    'available',
    auth.uid(),
    auth.uid()
  )
  returning id into detail_id;

  perform public.nostra_upsert_used_purchase_accounting_v92(detail_id);
  return v_vehicle_id;
end;
$$;

create or replace function public.update_used_vehicle_v92(
  p_vehicle_id bigint,
  p_brand text,
  p_model text,
  p_version text,
  p_registration text,
  p_previous_owner text,
  p_purchase_date date,
  p_purchase_price numeric,
  p_resale_price numeric,
  p_quantity integer,
  p_images jsonb,
  p_description text,
  p_condition text,
  p_internal_notes text,
  p_trunk_capacity text,
  p_top_speed text,
  p_power text,
  p_sort_order integer,
  p_published boolean
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  detail_id bigint;
  normalized_registration text := nullif(upper(btrim(coalesce(p_registration, ''))), '');
  normalized_condition text := lower(btrim(coalesce(p_condition, 'good')));
begin
  if not public.nostra_can_manage_used_vehicles_v92() then
    raise exception using message = 'forbidden';
  end if;

  select detail.id into detail_id
  from public.used_vehicle_details detail
  join public.catalog_vehicles vehicle on vehicle.id = detail.vehicle_id
  where detail.vehicle_id = p_vehicle_id
    and vehicle.catalog_type = 'used'
  for update of detail, vehicle;

  if not found then
    raise exception using message = 'vehicle_not_found';
  end if;

  if btrim(coalesce(p_brand, '')) = ''
    or btrim(coalesce(p_model, '')) = ''
    or p_purchase_date is null
    or coalesce(p_purchase_price, 0) <= 0
    or coalesce(p_resale_price, 0) <= 0
    or coalesce(p_quantity, 0) <= 0
  then
    raise exception using message = 'invalid_used_vehicle';
  end if;

  if normalized_condition not in ('excellent', 'very_good', 'good', 'fair', 'repair') then
    normalized_condition := 'good';
  end if;

  if normalized_registration is not null and exists (
    select 1
    from public.used_vehicle_details
    where lower(registration) = lower(normalized_registration)
      and vehicle_id <> p_vehicle_id
  ) then
    raise exception using message = 'registration_already_exists';
  end if;

  update public.catalog_vehicles
  set brand = btrim(p_brand),
      model = btrim(p_model),
      trunk_capacity = coalesce(btrim(p_trunk_capacity), ''),
      top_speed = coalesce(btrim(p_top_speed), ''),
      power = coalesce(btrim(p_power), ''),
      price = p_resale_price,
      description = coalesce(p_description, ''),
      images = coalesce(p_images, '[]'::jsonb),
      published = coalesce(p_published, false),
      sort_order = greatest(coalesce(p_sort_order, 0), 0),
      catalog_type = 'used',
      used_condition = normalized_condition,
      updated_at = now()
  where id = p_vehicle_id;

  update public.used_vehicle_details
  set version = nullif(btrim(coalesce(p_version, '')), ''),
      registration = normalized_registration,
      previous_owner = nullif(btrim(coalesce(p_previous_owner, '')), ''),
      purchase_date = p_purchase_date,
      purchase_price = p_purchase_price,
      resale_price = p_resale_price,
      purchase_quantity = greatest(p_quantity, 1),
      vehicle_condition = normalized_condition,
      internal_notes = nullif(btrim(coalesce(p_internal_notes, '')), ''),
      updated_by = auth.uid(),
      updated_at = now()
  where id = detail_id;

  perform public.nostra_upsert_used_purchase_accounting_v92(detail_id);

  -- Une correction du prix de rachat recalcule aussi les marges historiques
  -- sans modifier le prix de vente ni la date des ventes.
  for detail_id in
    update public.used_vehicle_sales
    set unit_purchase_price = p_purchase_price,
        total_purchase_price = p_purchase_price * quantity,
        margin = total_sale_price - (p_purchase_price * quantity),
        updated_at = now()
    where vehicle_id = p_vehicle_id
    returning id
  loop
    perform public.nostra_upsert_used_sale_accounting_v92(detail_id);
  end loop;
end;
$$;

create or replace function public.delete_used_vehicle_v92(p_vehicle_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  detail_id bigint;
begin
  if not public.nostra_can_manage_used_vehicles_v92() then
    raise exception using message = 'forbidden';
  end if;

  select id into detail_id
  from public.used_vehicle_details
  where vehicle_id = p_vehicle_id;

  if not found then
    raise exception using message = 'vehicle_not_found';
  end if;

  if exists (
    select 1
    from public.orders order_row
    cross join lateral jsonb_array_elements(coalesce(order_row.items, '[]'::jsonb)) item
    where item ->> 'item_type' = 'vehicle'
      and nullif(item ->> 'vehicle_id', '')::bigint = p_vehicle_id
      and order_row.status in ('pending', 'confirmed', 'preparing', 'ready')
  ) then
    raise exception using message = 'vehicle_has_active_order';
  end if;

  if exists (
    select 1 from public.used_vehicle_sales where vehicle_id = p_vehicle_id
  ) or exists (
    select 1
    from public.orders order_row
    cross join lateral jsonb_array_elements(coalesce(order_row.items, '[]'::jsonb)) item
    where item ->> 'item_type' = 'vehicle'
      and nullif(item ->> 'vehicle_id', '')::bigint = p_vehicle_id
      and order_row.status = 'completed'
  ) then
    raise exception using message = 'vehicle_has_sales';
  end if;

  delete from public.accounting_entries
  where nostra_source_type = 'used_purchase'
    and nostra_source_id = detail_id::text;

  delete from public.cart_items where vehicle_id = p_vehicle_id;
  delete from public.cart_items where related_vehicle_id = p_vehicle_id;
  delete from public.catalog_vehicles where id = p_vehicle_id;
end;
$$;

create or replace function public.update_used_vehicle_stock_v92(
  p_vehicle_id bigint,
  p_stock_quantity integer,
  p_sale_status text default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  next_status text := lower(btrim(coalesce(p_sale_status, '')));
begin
  if not public.nostra_can_manage_used_vehicles_v92() then
    raise exception using message = 'forbidden';
  end if;

  if not exists (
    select 1 from public.catalog_vehicles
    where id = p_vehicle_id and catalog_type = 'used'
  ) then
    raise exception using message = 'vehicle_not_found';
  end if;

  if next_status not in ('available', 'reserved', 'sold') then
    next_status := case when greatest(p_stock_quantity, 0) > 0 then 'available' else 'sold' end;
  end if;

  if next_status = 'available' and greatest(p_stock_quantity, 0) <= 0 then
    raise exception using message = 'available_requires_stock';
  end if;

  if next_status = 'sold' then
    p_stock_quantity := 0;
  end if;

  if next_status = 'available' and exists (
    select 1
    from public.orders order_row
    cross join lateral jsonb_array_elements(coalesce(order_row.items, '[]'::jsonb)) item
    where order_row.status in ('pending', 'confirmed', 'preparing', 'ready')
      and item ->> 'item_type' = 'vehicle'
      and nullif(item ->> 'vehicle_id', '')::bigint = p_vehicle_id
  ) then
    raise exception using message = 'vehicle_has_active_order';
  end if;

  update public.catalog_vehicles
  set stock_quantity = greatest(p_stock_quantity, 0),
      used_vehicle_status = next_status,
      updated_at = now()
  where id = p_vehicle_id;

  update public.used_vehicle_details
  set sale_status = next_status,
      updated_by = auth.uid(),
      updated_at = now()
  where vehicle_id = p_vehicle_id;
end;
$$;

create or replace function public.publish_used_vehicle_v92(
