create or replace function public.nostra_upsert_used_order_document_v92(
  p_order_id bigint,
  p_document_type text
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  order_row public.orders%rowtype;
  invoice_id bigint;
  invoice_number text;
  title text;
  payload jsonb;
  used_items jsonb := '[]'::jsonb;
  used_total numeric(14,2) := 0;
begin
  select * into order_row
  from public.orders
  where id = p_order_id;

  if not found then
    return null;
  end if;

  select
    coalesce(jsonb_agg(line.item order by line.ordinality), '[]'::jsonb),
    coalesce(sum(
      greatest(1, coalesce(nullif(line.item ->> 'quantity', '')::numeric, 1))
      * greatest(0, coalesce(nullif(line.item ->> 'unit_price', '')::numeric, 0))
    ), 0)
  into used_items, used_total
  from jsonb_array_elements(coalesce(order_row.items, '[]'::jsonb))
    with ordinality as line(item, ordinality)
  where (
    coalesce(line.item ->> 'item_type', 'vehicle') = 'vehicle'
    and exists (
      select 1
      from public.catalog_vehicles vehicle
      where vehicle.id = nullif(line.item ->> 'vehicle_id', '')::bigint
        and vehicle.catalog_type = 'used'
    )
  ) or (
    line.item ->> 'item_type' = 'delivery'
    and exists (
      select 1
      from public.catalog_vehicles vehicle
      where vehicle.id = nullif(line.item ->> 'related_vehicle_id', '')::bigint
        and vehicle.catalog_type = 'used'
    )
  );

  if jsonb_array_length(used_items) = 0 then
    return null;
  end if;

  if p_document_type = 'order_form' then
    invoice_number := 'VO-BC-' || order_row.order_number;
    title := 'Bon de commande — véhicule d’occasion';
  else
    invoice_number := 'VO-FA-' || order_row.order_number;
    title := 'Facture — véhicule d’occasion';
    p_document_type := 'invoice';
  end if;

  payload := jsonb_build_object(
    'order_number', order_row.order_number,
    'customer_name', order_row.customer_name,
    'customer_note', order_row.customer_note,
    'admin_note', order_row.admin_note,
    'total', used_total,
    'items', used_items,
    'confirmed_at', case when p_document_type = 'order_form' then now() else null end,
    'delivered_at', case when p_document_type = 'invoice' then now() else null end,
    'catalogue', 'Véhicules d’occasion'
  );

  insert into public.invoices (
    user_id,
    invoice_number,
    status,
    amount,
    issued_at,
    download_url,
    order_id,
    document_type,
    document_title,
    document_payload
  ) values (
    order_row.user_id,
    invoice_number,
    'issued',
    used_total,
    now(),
    null,
    order_row.id,
    p_document_type,
    title,
    payload
  )
  on conflict (invoice_number)
  do update set
    status = excluded.status,
    amount = excluded.amount,
    order_id = excluded.order_id,
    document_type = excluded.document_type,
    document_title = excluded.document_title,
    document_payload = excluded.document_payload
  returning id into invoice_id;

  return invoice_id;
end;
$$;

create or replace function public.nostra_validate_used_order_v92()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  item jsonb;
  v_vehicle_id bigint;
  vehicle_row public.catalog_vehicles%rowtype;
begin
  -- Une simple évolution de statut d'une commande active (confirmée, prête,
  -- terminée...) ne doit pas être bloquée par le statut « réservé » posé après
  -- sa création. La vérification concerne la création et la réactivation d'une
  -- commande précédemment annulée.
  if tg_op = 'UPDATE' and not (old.status = 'cancelled' and new.status <> 'cancelled') then
    return new;
  end if;

  for item in
    select value
    from jsonb_array_elements(coalesce(new.items, '[]'::jsonb))
  loop
    if coalesce(item ->> 'item_type', 'vehicle') <> 'vehicle' then
      continue;
    end if;

    v_vehicle_id := nullif(item ->> 'vehicle_id', '')::bigint;
    if v_vehicle_id is null then
      continue;
    end if;

    select * into vehicle_row
    from public.catalog_vehicles
    where id = v_vehicle_id
      and catalog_type = 'used';

    if found and vehicle_row.used_vehicle_status <> 'available' then
      raise exception using message = 'used_vehicle_unavailable';
    end if;
  end loop;

  return new;
end;
$$;

create or replace function public.nostra_sync_used_order_v92()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  source_order public.orders%rowtype;
  item jsonb;
  v_vehicle_id bigint;
  quantity integer;
  unit_sale_price numeric(14,2);
  detail_row public.used_vehicle_details%rowtype;
  vehicle_row public.catalog_vehicles%rowtype;
  sale_id bigint;
  has_used_vehicle boolean := false;
begin
  if tg_op = 'DELETE' then
    source_order := old;
  else
    source_order := new;
  end if;

  for item in
    select value
    from jsonb_array_elements(coalesce(source_order.items, '[]'::jsonb))
  loop
    if item ->> 'item_type' <> 'vehicle' then
      continue;
    end if;

    v_vehicle_id := nullif(item ->> 'vehicle_id', '')::bigint;
    if v_vehicle_id is null then
      continue;
    end if;

    select * into vehicle_row
    from public.catalog_vehicles
    where id = v_vehicle_id
      and catalog_type = 'used';

    if not found then
      continue;
    end if;

    has_used_vehicle := true;
    quantity := greatest(1, coalesce((item ->> 'quantity')::integer, 1));
    unit_sale_price := greatest(0, coalesce((item ->> 'unit_price')::numeric, vehicle_row.price));

    select detail.* into detail_row
    from public.used_vehicle_details detail
    where detail.vehicle_id = vehicle_row.id;

    if tg_op = 'DELETE' or source_order.status = 'cancelled' then
      for sale_id in
        select sale.id
        from public.used_vehicle_sales sale
        where sale.order_id = source_order.id
          and sale.vehicle_id = vehicle_row.id
      loop
        delete from public.accounting_entries
        where nostra_source_type = 'used_sale'
          and nostra_source_id = sale_id::text;
      end loop;

      delete from public.used_vehicle_sales
      where order_id = source_order.id
        and vehicle_id = vehicle_row.id;

      update public.used_vehicle_details
      set actual_sale_price = null,
          actual_margin = null,
          sold_at = null,
          sold_order_id = null,
          updated_at = now()
      where vehicle_id = vehicle_row.id
        and sold_order_id = source_order.id;

      perform public.nostra_refresh_used_vehicle_status_v92(vehicle_row.id);

    elsif source_order.status = 'completed' then
      insert into public.used_vehicle_sales (
        vehicle_id,
        order_id,
        order_number,
        user_id,
        customer_name,
        vehicle_name,
        quantity,
        unit_purchase_price,
        unit_sale_price,
        total_purchase_price,
        total_sale_price,
        margin,
        sold_at,
        updated_at
      ) values (
        vehicle_row.id,
        source_order.id,
        source_order.order_number,
        source_order.user_id,
        coalesce(source_order.customer_name, ''),
        btrim(vehicle_row.brand || ' ' || vehicle_row.model),
        quantity,
        coalesce(detail_row.purchase_price, 0),
        unit_sale_price,
        coalesce(detail_row.purchase_price, 0) * quantity,
        unit_sale_price * quantity,
        (unit_sale_price - coalesce(detail_row.purchase_price, 0)) * quantity,
        now(),
        now()
      )
      on conflict (order_id, vehicle_id)
      do update set
        order_number = excluded.order_number,
        user_id = excluded.user_id,
        customer_name = excluded.customer_name,
        vehicle_name = excluded.vehicle_name,
        quantity = excluded.quantity,
        unit_purchase_price = excluded.unit_purchase_price,
        unit_sale_price = excluded.unit_sale_price,
        total_purchase_price = excluded.total_purchase_price,
        total_sale_price = excluded.total_sale_price,
        margin = excluded.margin,
        sold_at = excluded.sold_at,
        updated_at = now()
      returning id into sale_id;

      perform public.nostra_upsert_used_sale_accounting_v92(sale_id);

      update public.used_vehicle_details
      set actual_sale_price = unit_sale_price,
          actual_margin = (unit_sale_price - coalesce(purchase_price, 0)) * quantity,
          sold_at = now(),
          sold_order_id = source_order.id,
          updated_at = now()
      where vehicle_id = vehicle_row.id;

      perform public.nostra_refresh_used_vehicle_status_v92(vehicle_row.id);

    else
      -- Une commande peut être repassée de « terminée » à un statut actif pendant
      -- les tests. Dans ce cas, retire uniquement la vente comptable liée à cette
      -- commande, sans toucher à la commande ni au stock déjà géré par le moteur
      -- de commandes existant.
      for sale_id in
        select sale.id
        from public.used_vehicle_sales sale
        where sale.order_id = source_order.id
          and sale.vehicle_id = vehicle_row.id
      loop
        delete from public.accounting_entries
        where nostra_source_type = 'used_sale'
          and nostra_source_id = sale_id::text;
      end loop;

      delete from public.used_vehicle_sales
      where order_id = source_order.id
        and vehicle_id = vehicle_row.id;

      update public.used_vehicle_details
      set actual_sale_price = null,
          actual_margin = null,
          sold_at = null,
          sold_order_id = null,
          updated_at = now()
      where vehicle_id = vehicle_row.id
        and sold_order_id = source_order.id;

      perform public.nostra_refresh_used_vehicle_status_v92(vehicle_row.id);
    end if;
  end loop;

  if has_used_vehicle then
    if tg_op = 'DELETE' or source_order.status = 'cancelled' then
      delete from public.invoices
      where order_id = source_order.id
        and invoice_number in (
          'VO-BC-' || source_order.order_number,
          'VO-FA-' || source_order.order_number
        );
    elsif source_order.status in ('confirmed', 'preparing', 'ready', 'completed') then
      perform public.nostra_upsert_used_order_document_v92(source_order.id, 'order_form');
      if source_order.status = 'completed' then
        perform public.nostra_upsert_used_order_document_v92(source_order.id, 'invoice');
      else
        delete from public.invoices
        where order_id = source_order.id
          and invoice_number = 'VO-FA-' || source_order.order_number;
      end if;
    else
      -- Une commande encore en attente ne doit pas conserver une facture créée
      -- lors d'un ancien passage au statut « terminée ».
      delete from public.invoices
      where order_id = source_order.id
        and invoice_number = 'VO-FA-' || source_order.order_number;
    end if;
  end if;

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

