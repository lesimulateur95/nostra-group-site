-- -----------------------------------------------------------------------------
-- 5) SOUSCRIPTION GARANTIE NOSTRA CARE
-- -----------------------------------------------------------------------------
create or replace function public.nostra_subscribe_warranty_v163(
  p_customer_vehicle_id bigint,
  p_plan_id bigint,
  p_start_at timestamptz default now()
)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  v_uid uuid := auth.uid();
  v_vehicle record;
  v_plan record;
  v_id bigint;
  v_number text;
  v_start timestamptz := coalesce(p_start_at,now());
begin
  if v_uid is null then raise exception using message='not_authenticated'; end if;
  select id,user_id into v_vehicle from public.customer_vehicles where id=p_customer_vehicle_id and user_id=v_uid and garage_status <> 'cancelled';
  if not found then raise exception using message='vehicle_not_found'; end if;
  select * into v_plan from public.motors_warranty_plans_v163 where id=p_plan_id and active;
  if not found then raise exception using message='warranty_plan_not_found'; end if;
  if exists(select 1 from public.motors_warranty_contracts_v163 where user_id=v_uid and customer_vehicle_id=p_customer_vehicle_id and status in ('pending_payment','active') and ends_at>now()) then
    raise exception using message='warranty_already_exists';
  end if;
  v_number := 'NG-' || to_char(now(),'YYYYMMDD') || '-' || upper(substr(replace(gen_random_uuid()::text,'-',''),1,7));
  insert into public.motors_warranty_contracts_v163(contract_number,user_id,customer_vehicle_id,plan_id,plan_name,duration_days,amount,deductible,starts_at,ends_at,status,coverage_snapshot)
  values(v_number,v_uid,p_customer_vehicle_id,v_plan.id,v_plan.name,v_plan.duration_days,v_plan.price,v_plan.deductible,v_start,v_start+make_interval(days=>v_plan.duration_days),'pending_payment',jsonb_build_object('engine',v_plan.engine,'gearbox',v_plan.gearbox,'electronics',v_plan.electronics,'suspension',v_plan.suspension,'bodywork',v_plan.bodywork,'tyres',v_plan.tyres)) returning id into v_id;
  return jsonb_build_object('id',v_id,'contract_number',v_number,'amount',v_plan.price,'duration_days',v_plan.duration_days);
end;
$$;
grant execute on function public.nostra_subscribe_warranty_v163(bigint,bigint,timestamptz) to authenticated;

-- -----------------------------------------------------------------------------
-- 6) RÉCEPTION FOURNISSEUR : STOCK + COÛT RÉEL + EXEMPLAIRES V162
-- -----------------------------------------------------------------------------
create or replace function public.nostra_receive_supplier_order_v163(p_order_id bigint)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  v_order record;
  v_item record;
  v_total_qty integer := 0;
  v_total_units integer := 0;
  v_transport_per_unit numeric(14,2) := 0;
  i integer;
begin
  if not public.has_nostra_dashboard_access() then raise exception using message='forbidden'; end if;
  select * into v_order from public.motors_supplier_orders_v163 where id=p_order_id for update;
  if not found then raise exception using message='supplier_order_not_found'; end if;
  if v_order.status='received' then return jsonb_build_object('already_received',true); end if;
  select coalesce(sum(quantity),0)::integer into v_total_units from public.motors_supplier_order_items_v163 where supplier_order_id=p_order_id;
  if v_total_units>0 then v_transport_per_unit := round(coalesce(v_order.inbound_transport_cost,0)/v_total_units,2); end if;
  for v_item in select * from public.motors_supplier_order_items_v163 where supplier_order_id=p_order_id loop
    update public.catalog_vehicles set stock_quantity=coalesce(stock_quantity,0)+v_item.quantity,updated_at=now() where id=v_item.catalog_vehicle_id;
    update public.motors_supplier_order_items_v163 set received_quantity=v_item.quantity where id=v_item.id;
    insert into public.motors_vehicle_costs_v163(catalog_vehicle_id,supplier_id,purchase_cost,inbound_transport_per_unit,preparation_cost,other_cost,updated_at,updated_by)
    values(v_item.catalog_vehicle_id,v_order.supplier_id,v_item.unit_purchase_cost,v_transport_per_unit,v_item.preparation_cost_per_unit,case when v_total_units>0 then round(coalesce(v_order.other_cost,0)/v_total_units,2) else 0 end,now(),auth.uid())
    on conflict(catalog_vehicle_id) do update set supplier_id=excluded.supplier_id,purchase_cost=excluded.purchase_cost,inbound_transport_per_unit=excluded.inbound_transport_per_unit,preparation_cost=excluded.preparation_cost,other_cost=excluded.other_cost,updated_at=now(),updated_by=auth.uid();
    begin
      for i in 1..v_item.quantity loop
        execute format('insert into public.motors_physical_vehicle_units_v162(unit_code,catalog_vehicle_id,status,location) values ($1,$2,$3,$4)')
        using 'NM-'||v_item.catalog_vehicle_id||'-'||upper(substr(replace(gen_random_uuid()::text,'-',''),1,7)),v_item.catalog_vehicle_id,'arrived','Réception fournisseur';
      end loop;
    exception when undefined_table then null;
    end;
    v_total_qty := v_total_qty + v_item.quantity;
  end loop;
  update public.motors_supplier_orders_v163 set status='received',received_at=now(),updated_at=now() where id=p_order_id;
  return jsonb_build_object('received_quantity',v_total_qty);
end;
$$;
grant execute on function public.nostra_receive_supplier_order_v163(bigint) to authenticated;

