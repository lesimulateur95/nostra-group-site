create table if not exists public.motors_supplier_orders_v163 (
  id bigint generated by default as identity primary key,
  order_number text not null unique,
  supplier_id bigint not null references public.motors_suppliers_v163(id) on delete restrict,
  status text not null default 'draft' check (status in ('draft','ordered','confirmed','in_transit','arrived','received','cancelled')),
  ordered_at timestamptz,
  expected_at timestamptz,
  received_at timestamptz,
  inbound_transport_cost numeric(14,2) not null default 0,
  other_cost numeric(14,2) not null default 0,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null
);

create table if not exists public.motors_supplier_order_items_v163 (
  id bigint generated by default as identity primary key,
  supplier_order_id bigint not null references public.motors_supplier_orders_v163(id) on delete cascade,
  catalog_vehicle_id bigint not null references public.catalog_vehicles(id) on delete restrict,
  quantity integer not null default 1 check (quantity > 0),
  unit_purchase_cost numeric(14,2) not null default 0,
  preparation_cost_per_unit numeric(14,2) not null default 0,
  received_quantity integer not null default 0 check (received_quantity >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.motors_vehicle_costs_v163 (
  catalog_vehicle_id bigint primary key references public.catalog_vehicles(id) on delete cascade,
  supplier_id bigint references public.motors_suppliers_v163(id) on delete set null,
  purchase_cost numeric(14,2) not null default 0,
  inbound_transport_per_unit numeric(14,2) not null default 0,
  preparation_cost numeric(14,2) not null default 0,
  other_cost numeric(14,2) not null default 0,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id) on delete set null
);

